package filemap

import (
	"fmt"
	"path/filepath"
	"regexp"
	"strings"

	"github.com/kaushal/skim/internal/digest"
)

var (
	// haskellModule matches the module declaration; groups: (1) qualified module name.
	haskellModule = regexp.MustCompile(`^module\s+([A-Z][A-Za-z0-9._']*)`)

	// haskellData matches data or newtype type declarations at column 0.
	// Groups: (1) type name.
	haskellData = regexp.MustCompile(`^(?:data|newtype)\s+([A-Z][A-Za-z0-9_']*)`)

	// haskellTypeDecl matches type alias / type family declarations.
	// Groups: (1) type name.
	haskellTypeDecl = regexp.MustCompile(`^type\s+(?:family\s+)?([A-Z][A-Za-z0-9_']*)`)

	// haskellClassDecl matches typeclass declarations; skips an optional
	// constraint context ("… =>") before the class name.
	// Groups: (1) class name.
	haskellClassDecl = regexp.MustCompile(`^class\s+(?:.*=>\s*)?([A-Z][A-Za-z0-9_']*)`)

	// haskellFnNameRe validates a single lowercase Haskell identifier
	// (used to accept or reject parts of a type-signature prefix).
	haskellFnNameRe = regexp.MustCompile(`^[a-z_][A-Za-z0-9_']*$`)

	haskellGenerated = regexp.MustCompile(`DO NOT EDIT|auto.?generated|This file was (automatically )?generated|Generated by|@generated`)
)

// parseHaskellFile builds a FileMap for a Haskell source file.
//
// Haskell's layout rule means every top-level declaration begins at column 0;
// continuation lines are always indented. This lets us collect all structural
// information by processing only unindented lines.
//
// The entire file maps to a single entry (the module); the Kind label lists
// type/class names followed by function names, up to 4 with +N overflow.
func parseHaskellFile(src, filePath string) (digest.FileMap, bool) {
	lines := splitLines(src)
	if len(lines) == 0 {
		return digest.FileMap{}, false
	}
	if !hasHaskellStructure(lines) {
		return digest.FileMap{}, false
	}

	generated := false
	for _, l := range lines[:min(len(lines), 10)] {
		if haskellGenerated.MatchString(l) {
			generated = true
			break
		}
	}

	var moduleName string
	var types []string // data/newtype/type/class names
	var fns []string   // top-level function names from type signatures
	seenTypes := make(map[string]bool)
	seenFns := make(map[string]bool)
	inBlockComment := false

	for _, raw := range lines {
		trimmed := strings.TrimSpace(raw)
		if trimmed == "" {
			continue
		}

		// Block comment {- ... -} (may span lines).
		if inBlockComment {
			if idx := strings.Index(trimmed, "-}"); idx >= 0 {
				inBlockComment = false
			}
			continue
		}
		// Opening {-  but not a pragma {-#.
		if strings.HasPrefix(trimmed, "{-") && !strings.HasPrefix(trimmed, "{-#") {
			if !strings.Contains(trimmed, "-}") {
				inBlockComment = true
			}
			continue
		}

		// Skip lines with leading whitespace — these are continuation lines
		// or indented definitions inside class/instance/where blocks.
		if len(raw) > 0 && (raw[0] == ' ' || raw[0] == '\t') {
			continue
		}

		// Skip line comments.
		if strings.HasPrefix(trimmed, "--") {
			continue
		}

		// Skip pragmas {-# … #-}.
		if strings.HasPrefix(trimmed, "{-#") {
			continue
		}

		// Skip import declarations.
		if strings.HasPrefix(trimmed, "import ") || trimmed == "import" {
			continue
		}

		// Module declaration.
		if m := haskellModule.FindStringSubmatch(raw); m != nil {
			moduleName = m[1]
			continue
		}

		// data / newtype type declaration.
		if m := haskellData.FindStringSubmatch(raw); m != nil {
			name := m[1]
			if !seenTypes[name] {
				types = append(types, name)
				seenTypes[name] = true
			}
			continue
		}

		// type / type family alias.
		if m := haskellTypeDecl.FindStringSubmatch(raw); m != nil {
			name := m[1]
			if !seenTypes[name] {
				types = append(types, name)
				seenTypes[name] = true
			}
			continue
		}

		// class declaration.
		if m := haskellClassDecl.FindStringSubmatch(raw); m != nil {
			name := m[1]
			if !seenTypes[name] {
				types = append(types, name)
				seenTypes[name] = true
			}
			continue
		}

		// instance — skip (too noisy; omit from file map).
		if strings.HasPrefix(raw, "instance ") {
			continue
		}

		// Top-level type signature: "foo :: Type" or "foo, bar :: Type".
		for _, name := range haskellFnNamesFromSig(raw) {
			if !isHaskellKeyword(name) && !seenFns[name] {
				fns = append(fns, name)
				seenFns[name] = true
			}
		}
	}

	if moduleName == "" && len(types) == 0 && len(fns) == 0 {
		return digest.FileMap{}, false
	}

	// Derive the display name: module name takes priority, else file stem.
	name := moduleName
	if name == "" {
		base := filepath.Base(filePath)
		name = strings.TrimSuffix(base, filepath.Ext(base))
	}

	// Kind label: types first (more structural), then functions.
	combined := append(types, fns...)
	label := haskellLabel(name, combined)

	var symbols []string
	for _, t := range types {
		symbols = append(symbols, "type "+t)
	}
	for _, f := range fns {
		symbols = append(symbols, "fn "+f)
	}

	return digest.FileMap{
		Summary: haskellSummary(name, len(types), len(fns), generated),
		Map: []digest.MapEntry{{
			Lines: lineRange(1, len(lines)),
			Kind:  label,
		}},
		Symbols: symbols,
	}, true
}

// haskellFnNamesFromSig extracts function names from a top-level type
// signature line of the form:
//
//	foo :: Type
//	foo, bar, baz :: Type
//
// It splits at the first "::", takes the left side, and validates each
// comma-separated segment as a simple lowercase Haskell identifier. Lines
// like "foreign import ccall "f" cFoo :: …" are rejected because the prefix
// contains spaces and quotes.
func haskellFnNamesFromSig(raw string) []string {
	idx := strings.Index(raw, "::")
	if idx < 0 {
		return nil
	}
	prefix := strings.TrimSpace(raw[:idx])
	var names []string
	for _, part := range strings.Split(prefix, ",") {
		name := strings.TrimSpace(part)
		if haskellFnNameRe.MatchString(name) {
			names = append(names, name)
		}
	}
	return names
}

func isHaskellKeyword(s string) bool {
	switch s {
	case "as", "case", "class", "data", "default", "deriving", "do",
		"else", "forall", "foreign", "hiding", "if", "import", "in",
		"infix", "infixl", "infixr", "instance", "let", "module",
		"newtype", "of", "qualified", "then", "type", "where":
		return true
	}
	return false
}

func haskellLabel(moduleName string, names []string) string {
	label := "module " + moduleName
	if len(names) == 0 {
		return label
	}
	displayed := names
	suffix := ""
	if len(displayed) > 4 {
		displayed = displayed[:4]
		suffix = fmt.Sprintf(" (+%d)", len(names)-4)
	}
	return label + " — " + strings.Join(displayed, ", ") + suffix
}

func haskellSummary(moduleName string, typeCount, fnCount int, generated bool) string {
	s := "Haskell — " + moduleName
	var parts []string
	if typeCount == 1 {
		parts = append(parts, "1 type")
	} else if typeCount > 1 {
		parts = append(parts, fmt.Sprintf("%d types", typeCount))
	}
	if fnCount == 1 {
		parts = append(parts, "1 function")
	} else if fnCount > 1 {
		parts = append(parts, fmt.Sprintf("%d functions", fnCount))
	}
	if len(parts) > 0 {
		s += ", " + strings.Join(parts, ", ")
	}
	if generated {
		s += " — generated, do not edit directly"
	}
	return s
}

func hasHaskellStructure(lines []string) bool {
	for _, l := range lines {
		if haskellModule.MatchString(l) ||
			haskellData.MatchString(l) ||
			haskellTypeDecl.MatchString(l) ||
			haskellClassDecl.MatchString(l) {
			return true
		}
	}
	return false
}
