package filemap_test

import (
	"strings"
	"testing"

	"github.com/kaushal/skim/internal/filemap"
)

const simpleGoFile = `// Package auth provides JWT-based authentication helpers.
package auth

import (
	"errors"
	"time"
)

// ErrExpired is returned when a token has passed its expiry time.
var ErrExpired = errors.New("token expired")

// Token holds the parsed contents of a JWT.
type Token struct {
	Subject  string
	Expiry   time.Time
	IsAdmin  bool
}

// Parse decodes and validates a JWT string.
func Parse(raw string) (Token, error) {
	if raw == "" {
		return Token{}, ErrExpired
	}
	return Token{Subject: "user"}, nil
}

// Validate checks whether t has not expired.
func (t Token) Validate() error {
	if time.Now().After(t.Expiry) {
		return ErrExpired
	}
	return nil
}
`

func TestGenerate_GoFile_ReturnsFalseForTestFile(t *testing.T) {
	_, ok := filemap.Generate(simpleGoFile, "internal/auth/auth_test.go")
	if ok {
		t.Error("should not generate map for _test.go files")
	}
}

func TestGenerate_GoFile_ReturnsFalseForUnsupportedExt(t *testing.T) {
	// .rb is not a supported extension — must fall through to the worker.
	_, ok := filemap.Generate(simpleGoFile, "auth.rb")
	if ok {
		t.Error("should return false for unsupported extension (.rb)")
	}
}

func TestGenerate_GoFile_ReturnsFalseForInvalidContent(t *testing.T) {
	_, ok := filemap.Generate(strings.Repeat("x\n", 100), "big.go")
	if ok {
		t.Error("should return false for content without package declaration")
	}
}

func TestGenerate_GoFile_SummaryFromDocComment(t *testing.T) {
	fm, ok := filemap.Generate(simpleGoFile, "internal/auth/auth.go")
	if !ok {
		t.Fatal("expected ok=true for valid Go file")
	}
	if !strings.Contains(fm.Summary, "auth") {
		t.Errorf("summary %q should mention package name", fm.Summary)
	}
	if fm.Summary == "" {
		t.Error("summary must not be empty")
	}
}

func TestGenerate_GoFile_MapNonEmpty(t *testing.T) {
	fm, ok := filemap.Generate(simpleGoFile, "auth.go")
	if !ok {
		t.Fatal("expected ok")
	}
	if len(fm.Map) == 0 {
		t.Error("map must not be empty")
	}
}

func TestGenerate_GoFile_HasExportedSymbols(t *testing.T) {
	fm, ok := filemap.Generate(simpleGoFile, "auth.go")
	if !ok {
		t.Fatal("expected ok")
	}
	syms := strings.Join(fm.Symbols, ",")
	if !strings.Contains(syms, "ErrExpired") {
		t.Errorf("symbols %q should contain ErrExpired", syms)
	}
	if !strings.Contains(syms, "Token") {
		t.Errorf("symbols %q should contain Token", syms)
	}
	if !strings.Contains(syms, "Parse") {
		t.Errorf("symbols %q should contain Parse", syms)
	}
}

func TestGenerate_GoFile_MapContainsFuncEntry(t *testing.T) {
	fm, ok := filemap.Generate(simpleGoFile, "auth.go")
	if !ok {
		t.Fatal("expected ok")
	}
	var hasParse bool
	for _, entry := range fm.Map {
		if strings.Contains(entry.Kind, "func Parse") {
			hasParse = true
		}
	}
	if !hasParse {
		t.Errorf("map entries should include func Parse; got: %v", fm.Map)
	}
}

