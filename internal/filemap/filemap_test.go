func TestGenerate_GoFile_SyntaxErrorsYieldPartialMap(t *testing.T) {
	// A file with a valid package declaration but a syntax error in a function
	// body should still produce a useful map via partial parse.
	partial := `package broken

func Good() string { return "ok" }

func Bad(  // missing closing paren
`
	fm, ok := filemap.Generate(partial, "broken.go")
	if !ok {
		t.Fatal("partial parse should still yield a map")
	}
	if len(fm.Map) == 0 {
		t.Error("partial map must not be empty")
	}
	// Good function should appear
	var hasGood bool
	for _, e := range fm.Map {
		if strings.Contains(e.Kind, "Good") {
			hasGood = true
		}
	}
	if !hasGood {
		t.Errorf("Good() should appear in partial map; entries: %v", fm.Map)
	}
}

func TestGenerate_GoFile_GeneratedFileNoted(t *testing.T) {
	gen := `// Code generated by protoc-gen-go. DO NOT EDIT.
package pb

type Foo struct{}
`
	fm, ok := filemap.Generate(gen, "foo.pb.go")
	if !ok {
		t.Fatal("expected ok for generated file")
	}
	if !strings.Contains(fm.Notes, "generated") {
		t.Errorf("notes %q should mention generated file", fm.Notes)
	}
}

func TestGenerate_GoFile_NoSymbolsDuplication(t *testing.T) {
	// A type with a method should list the type name once, not twice.
	src := `package foo

type Foo struct{}
func (f Foo) Bar() {}
func (f Foo) Baz() {}
`
	fm, ok := filemap.Generate(src, "foo.go")
	if !ok {
		t.Fatal("expected ok")
	}
	seen := map[string]int{}
	for _, s := range fm.Symbols {
		seen[s]++
	}
	for sym, n := range seen {
		if n > 1 {
			t.Errorf("symbol %q appears %d times, expected once", sym, n)
		}
	}
}
