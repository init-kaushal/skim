package filemap

import (
	"fmt"
	"regexp"
	"strings"

	"github.com/kaushal/skim/internal/digest"
)

var (
	// cppTopBlock matches a C++ type declaration at the start of a line.
	// Handles optional qualifiers (template instantiation residue, etc.) before
	// the keyword. Groups: (1) kind, (2) name.
	cppTopBlock = regexp.MustCompile(
		`^\s*(?:(?:template\s*<[^>]*>\s*)?)` + // optional template<...>
			`(?:(?:inline|static|extern|explicit|virtual|friend|constexpr|consteval|constinit|[[nodiscard]])\s+)*` +
			`(class|struct|union|enum(?:\s+class)?)\s+` +
			`(?:(?:__attribute__\s*\(\([^)]*\)\)\s*)*)` + // optional GCC attributes
			`(?:[A-Za-z_][A-Za-z0-9_]*\s+)*?` + // optional tag (e.g. "final")
			`([A-Za-z_][A-Za-z0-9_:]*)`) // name (may include :: for nested)
	// cppFunction matches a C++ function/method definition.
	// Groups: (1) name
	cppFunction = regexp.MustCompile(
		`^\s*(?:(?:virtual|static|inline|explicit|override|final|constexpr|consteval|[[nodiscard]]\s+))*` +
			`(?:~?[A-Za-z_][A-Za-z0-9_:<>*&, \t]*\s+)?` + // optional return type
			`(~?[A-Za-z_][A-Za-z0-9_]*)\s*\(`)
	// cppNamespace matches a namespace declaration.
	cppNamespace = regexp.MustCompile(`^\s*namespace\s+[A-Za-z_][A-Za-z0-9_:]*\s*[{$]|^\s*namespace\s*{`)
	// cppPreprocessor matches preprocessor lines to skip.
	cppPreprocessor = regexp.MustCompile(`^\s*#`)
	// cppExternC matches extern "C" blocks (they add no structural info).
	cppExternC = regexp.MustCompile(`^\s*extern\s+"C"\s*{`)
	// cppTypedefAnon matches "typedef struct/union/enum {" (anonymous typedef).
	// The type name comes from the closing "} Name;" line.
	cppTypedefAnon = regexp.MustCompile(`^\s*typedef\s+(struct|union|enum)\s*{`)
	// cppTypedefClose matches "} TypeName;" at the start of a line (multi-line typedef close).
	cppTypedefClose = regexp.MustCompile(`^\s*}\s*([A-Za-z_][A-Za-z0-9_]*)\s*;`)
	// cppTypedefInline extracts the alias name from a single-line typedef:
	// "typedef struct { ... } Name;" — matches "} Name;" anywhere in the line.
	cppTypedefInline = regexp.MustCompile(`}\s*([A-Za-z_][A-Za-z0-9_]*)\s*;`)
	// cppComment matches single-line C/C++ comments.
	cppComment = regexp.MustCompile(`^\s*//`)
	// cppGenerated detects generated C/C++ files.
	cppGenerated = regexp.MustCompile(`DO NOT EDIT|auto.?generated|This file was (automatically )?generated|Generated by|@generated`)
)

// cppBlock tracks one C/C++ type declaration while parsing.
type cppBlock struct {
	kind      string
	name      string
	startLine int
	endLine   int
	methods   []string
}

// parseCppFile builds a FileMap from a C/C++ source file. Each top-level
// type declaration (class, struct, union, enum class) becomes one map entry.
// Standalone functions and namespace blocks are tracked for depth but not
// emitted as entries.
func parseCppFile(src, _ string) (digest.FileMap, bool) {
	lines := splitLines(src)
	if len(lines) == 0 {
		return digest.FileMap{}, false
	}
	if !hasCppStructure(lines) {
		return digest.FileMap{}, false
	}

	generated := false
	for _, l := range lines[:min(len(lines), 10)] {
		if cppGenerated.MatchString(l) {
			generated = true
			break
		}
	}

	var blocks []*cppBlock
	var cur *cppBlock
	var pendingBlock *cppBlock
	depth := 0
	outerDepth := 0      // namespace / extern-C outer scope depth
	bcDepth := 0         // block comment depth (not nested in C/C++, but int for uniformity)
	rawStringDelim := "" // expected closing sequence for a multi-line raw string, e.g. )foo"
	inTypedef := false   // tracking a "typedef struct/union/enum { ... } Name;" block

	closeBlock := func(endLine int) {
		if cur != nil {
			cur.endLine = endLine
			blocks = append(blocks, cur)
			cur = nil
		}
	}

	for i, raw := range lines {
		lineNo := i + 1
		trimmed := strings.TrimSpace(raw)

		if trimmed == "" {
			continue
		}

		startedInBC := bcDepth > 0
		startedInRaw := rawStringDelim != ""

		if pendingBlock != nil {
			d := cppNetBraces(raw, &bcDepth, &rawStringDelim)
			if d > 0 {
				cur = pendingBlock
				depth = d
				pendingBlock = nil
			} else if d < 0 {
				pendingBlock = nil
			}
			continue
		}

		if cur != nil {
			// Collect methods at depth 1 BEFORE updating depth.
			if !startedInBC && !startedInRaw && depth == 1 && !cppPreprocessor.MatchString(raw) {
				if m := cppFunction.FindStringSubmatch(trimmed); m != nil {
					name := m[1]
					if !isCppKeyword(name) && name != cur.name {
						cur.methods = append(cur.methods, name)
					}
				}
			}
			depth += cppNetBraces(raw, &bcDepth, &rawStringDelim)
			if depth <= 0 {
				if inTypedef {
					if m := cppTypedefClose.FindStringSubmatch(trimmed); m != nil {
						cur.name = m[1]
					}
					inTypedef = false
				}
				closeBlock(lineNo)
				depth = 0
			}
			continue
		}

		// Top level (possibly inside a namespace).
		if startedInBC || startedInRaw {
			cppNetBraces(raw, &bcDepth, &rawStringDelim)
			continue
		}
		if cppPreprocessor.MatchString(raw) {
			continue
		}
		if cppComment.MatchString(raw) {
			continue
		}

		// extern "C" { ... } — track outer depth, don't emit.
		if cppExternC.MatchString(raw) {
			d := cppNetBraces(raw, &bcDepth, &rawStringDelim)
			outerDepth += d
			continue
		}

		// Namespace block — transparent scope.
		if cppNamespace.MatchString(raw) {
			d := cppNetBraces(raw, &bcDepth, &rawStringDelim)
			outerDepth += d
			continue
		}

		// C anonymous typedef: "typedef struct { ... } Name;"
		// The name is unknown until the closing "} Name;" line. For single-line
		// forms ("typedef struct { int x; } Point;") d == 0; capture the name
		// directly without opening a block.
		if m := cppTypedefAnon.FindStringSubmatch(trimmed); m != nil {
			kind := strings.TrimSpace(m[1])
			d := cppNetBraces(raw, &bcDepth, &rawStringDelim)
			if d > 0 {
				b := &cppBlock{kind: kind, name: "", startLine: lineNo}
				cur = b
				depth = d
				inTypedef = true
			} else if d == 0 {
				// Single-line form: "typedef struct { ... } Name;"
				// cppTypedefClose is anchored to line-start (for multi-line close),
				// so use the non-anchored cppTypedefInline to find "} Name;" anywhere.
				if mc := cppTypedefInline.FindStringSubmatch(trimmed); mc != nil {
					b := &cppBlock{kind: kind, name: mc[1], startLine: lineNo, endLine: lineNo}
					blocks = append(blocks, b)
				}
			}
			continue
		}

		// Type declaration.
		if m := cppTopBlock.FindStringSubmatch(trimmed); m != nil {
			kind := strings.TrimSpace(m[1])
			name := m[2]
			if idx := strings.LastIndex(name, "::"); idx >= 0 {
				name = name[idx+2:]
			}
			b := &cppBlock{kind: kind, name: name, startLine: lineNo}
			d := cppNetBraces(raw, &bcDepth, &rawStringDelim)
			if d > 0 {
				cur = b
				depth = d
			} else {
				// No opening brace yet; forward decl ("class Foo;") or split header.
				if !strings.Contains(trimmed, ";") {
					pendingBlock = b
				}
			}
			continue
		}

		// Bare brace changes at the outer level (closing namespace/extern "C").
		d := cppNetBraces(raw, &bcDepth, &rawStringDelim)
		if d < 0 && outerDepth > 0 {
			outerDepth += d
			if outerDepth < 0 {
				outerDepth = 0
			}
		}
	}
	closeBlock(len(lines))

	if len(blocks) == 0 {
		return digest.FileMap{}, false
	}

	var entries []digest.MapEntry
	var symbols []string
	for _, b := range blocks {
		label := cppBlockLabel(b)
		if len(symbols) < 40 {
			symbols = append(symbols, b.kind+" "+b.name)
		}
		entries = append(entries, digest.MapEntry{
			Lines: lineRange(b.startLine, b.endLine),
			Kind:  label,
		})
	}

	return digest.FileMap{
		Summary: cppSummary(blocks, generated),
		Map:     entries,
		Symbols: symbols,
	}, true
}

// cppNetBraces counts net brace depth for a C/C++ line, ignoring braces inside
// double-quoted strings, character literals, // comments, /* */ block comments,
// and C++ raw strings R"delimiter(...)delimiter". Both bcDepth and rawDelim
// carry state across lines for multi-line constructs:
//   - bcDepth: > 0 while inside a /* ... */ block comment.
//   - rawDelim: non-empty while inside a multi-line raw string; holds the
//     exact closing sequence (e.g. )foo") needed to end it.
func cppNetBraces(line string, bcDepth *int, rawDelim *string) int {
	depth := 0
	inStr := false

	// If we're inside a multi-line raw string from a previous line, scan for
	// the closing delimiter before processing anything else.
	i := 0
	if *rawDelim != "" {
		idx := strings.Index(line, *rawDelim)
		if idx < 0 {
			return 0 // still inside the raw string; no structural chars
		}
		i = idx + len(*rawDelim) // resume after the closing delimiter
		*rawDelim = ""
	}

	for ; i < len(line); i++ {
		ch := line[i]
		if *bcDepth > 0 {
			if ch == '*' && i+1 < len(line) && line[i+1] == '/' {
				*bcDepth--
				i++
			}
			continue
		}
		if inStr {
			if ch == '\\' {
				i++
				continue
			}
			if ch == '"' {
				inStr = false
			}
			continue
		}
		switch ch {
		case '"':
			inStr = true
		case '\'':
			// Character literal: skip to closing unescaped quote.
			i++
			for i < len(line) {
				if line[i] == '\\' {
					i++
				} else if line[i] == '\'' {
					break
				}
				i++
			}
		case 'R':
			// C++ raw string: R"delimiter(...)delimiter"
			if i+2 < len(line) && line[i+1] == '"' {
				j := i + 2
				delimStart := j
				for j < len(line) && line[j] != '(' && line[j] != '"' {
					j++
				}
				if j < len(line) && line[j] == '(' {
					delim := line[delimStart:j]
					closing := ")" + delim + "\""
					closeIdx := strings.Index(line[j+1:], closing)
					if closeIdx >= 0 {
						// Raw string opens and closes on the same line.
						i = j + 1 + closeIdx + len(closing) - 1
					} else {
						// Raw string opens here but doesn't close on this line.
						// Persist the closing sequence for subsequent lines.
						*rawDelim = closing
						return depth
					}
				}
				// If no '(' found it's not a raw string; fall through.
			}
		case '/':
			if i+1 < len(line) && line[i+1] == '/' {
				return depth
			}
			if i+1 < len(line) && line[i+1] == '*' {
				*bcDepth = 1
				i++
			}
		case '{':
			depth++
		case '}':
			depth--
		}
	}
	return depth
}

// isCppKeyword reports whether s is a C/C++ keyword that could appear in the
// broad function regex but is not a function name.
func isCppKeyword(s string) bool {
	switch s {
	case "if", "else", "for", "while", "do", "switch", "case", "break",
		"continue", "return", "goto", "try", "catch", "throw", "new", "delete",
		"sizeof", "alignof", "decltype", "typeid", "typeof", "static_assert",
		"class", "struct", "union", "enum", "namespace", "template", "typename",
		"virtual", "override", "final", "inline", "static", "extern", "const",
		"constexpr", "consteval", "constinit", "volatile", "mutable", "auto",
		"register", "friend", "explicit", "operator", "this", "nullptr",
		"true", "false", "using", "typedef", "public", "private", "protected":
		return true
	}
	return false
}

// cppBlockLabel builds the Kind label for a C++ block entry.
func cppBlockLabel(b *cppBlock) string {
	label := b.kind + " " + b.name
	if len(b.methods) == 0 {
		return label
	}
	displayed := b.methods
	suffix := ""
	if len(displayed) > 4 {
		displayed = displayed[:4]
		suffix = fmt.Sprintf(" (+%d)", len(b.methods)-4)
	}
	return label + " — " + strings.Join(displayed, ", ") + suffix
}

// cppSummary builds the top-level summary line.
func cppSummary(blocks []*cppBlock, generated bool) string {
	counts := map[string]int{}
	methodCount := 0
	for _, b := range blocks {
		counts[b.kind]++
		methodCount += len(b.methods)
	}

	ordered := []string{"class", "struct", "union", "enum", "enum class"}
	var parts []string
	for _, k := range ordered {
		n := counts[k]
		if n == 0 {
			continue
		}
		if n == 1 {
			parts = append(parts, "1 "+k)
		} else {
			words := strings.Fields(k)
			words[len(words)-1] += "s"
			parts = append(parts, fmt.Sprintf("%d %s", n, strings.Join(words, " ")))
		}
	}
	if methodCount == 1 {
		parts = append(parts, "1 method")
	} else if methodCount > 1 {
		parts = append(parts, fmt.Sprintf("%d methods", methodCount))
	}

	summary := "C/C++ — " + strings.Join(parts, ", ")
	if generated {
		summary += " — generated, do not edit directly"
	}
	return summary
}

// hasCppStructure returns true when at least one class/struct/union/enum
// declaration is present, including C-style anonymous typedef structs.
func hasCppStructure(lines []string) bool {
	for _, l := range lines {
		if cppTopBlock.MatchString(l) || cppTypedefAnon.MatchString(l) {
			return true
		}
	}
	return false
}
