package filemap

import (
	"fmt"
	"regexp"
	"strings"

	"github.com/kaushal/skim/internal/digest"
)

var (
	// scalaTopBlock matches a Scala type declaration.
	// Handles optional annotations (@annotation on same line) and modifiers.
	// Groups: (1) kind phrase, (2) name
	scalaTopBlock = regexp.MustCompile(
		`^\s*(?:(?:@\w+(?:\([^)]*\))?\s+)*)` + // optional inline annotations
			`(?:(?:private|protected|public|override|implicit|lazy)\s+)*` + // access modifiers only
			`((?:(?:case|sealed|abstract|final|open)\s+)*` + // type-shaping qualifiers in group 1
			`(?:class|object|trait|enum))\s+` +
			`([A-Za-z_][A-Za-z0-9_]*)`)

	// scalaDef matches a method/function declaration.
	// Groups: (1) name
	scalaDef = regexp.MustCompile(
		`^\s*(?:(?:@\w+(?:\([^)]*\))?\s+)*)` + // optional inline annotations
			`(?:(?:private|protected|override|implicit|inline|transparent|final|abstract|lazy)\s+)*` +
			`def\s+([A-Za-z_][A-Za-z0-9_?!]*)`) // "?" and "!" are valid Scala method name chars
	// scalaComment matches Scala single-line comments.
	scalaComment = regexp.MustCompile(`^\s*//`)
	// scalaImport matches import/package lines to skip.
	scalaImport = regexp.MustCompile(`^\s*(?:import|package)\s`)
	// scalaAnnotation matches standalone annotation lines.
	scalaAnnotation = regexp.MustCompile(`^\s*@`)
	// scalaGenerated detects generated Scala files.
	scalaGenerated = regexp.MustCompile(`DO NOT EDIT|auto.?generated|This file was (automatically )?generated|Generated by|@generated|scalapb`)
)

// scalaBlock tracks one Scala type declaration while parsing.
type scalaBlock struct {
	kind      string
	name      string
	startLine int
	endLine   int
	defs      []string
}

// parseScalaFile builds a FileMap from a Scala source file. Each top-level
// type declaration (class, object, trait, enum, case class, etc.) becomes one
// map entry; the Kind label lists up to 4 def names with +N overflow.
func parseScalaFile(src, _ string) (digest.FileMap, bool) {
	lines := splitLines(src)
	if len(lines) == 0 {
		return digest.FileMap{}, false
	}
	if !hasScalaStructure(lines) {
		return digest.FileMap{}, false
	}

	generated := false
	for _, l := range lines[:min(len(lines), 10)] {
		if scalaGenerated.MatchString(l) {
			generated = true
			break
		}
	}

	var blocks []*scalaBlock
	var cur *scalaBlock
	var pendingBlock *scalaBlock // waiting for opening "{"
	depth := 0
	bcDepth := 0       // block comment depth (not nested in Scala)
	inTripleQuote := false

	closeBlock := func(endLine int) {
		if cur != nil {
			cur.endLine = endLine
			blocks = append(blocks, cur)
			cur = nil
		}
	}

	for i, raw := range lines {
		lineNo := i + 1
		trimmed := strings.TrimSpace(raw)

		if trimmed == "" {
			continue
		}

		// Triple-quoted string tracking: toggle on odd count of """ per line.
		// Scala triple-quoted strings are always multi-line (the opening """ and
		// content are on separate lines in idiomatic usage), but handle the count
		// to be safe.
		tripleCount := strings.Count(trimmed, `"""`)
		if inTripleQuote {
			if tripleCount%2 == 1 {
				inTripleQuote = false
			}
			continue
		}
		if tripleCount%2 == 1 {
			inTripleQuote = true
			continue
		}

		startedInBC := bcDepth > 0

		if pendingBlock != nil {
			d := scalaNetBraces(raw, &bcDepth)
			if d > 0 {
				cur = pendingBlock
				depth = d
				pendingBlock = nil
				continue
			}
			if d < 0 {
				pendingBlock = nil
				continue
			}
			// d == 0: still no opening brace. If this line starts a new type
			// declaration, emit the current pendingBlock as body-less (it had no
			// braces — e.g. "case class Foo(...) extends Bar") and fall through
			// to process the new declaration normally.
			if !startedInBC && scalaTopBlock.MatchString(trimmed) {
				pendingBlock.endLine = lineNo - 1
				blocks = append(blocks, pendingBlock)
				pendingBlock = nil
				// Fall through to the top-level logic below.
			} else {
				continue // still waiting for "{"
			}
		}

		if cur != nil {
			// Collect defs at depth 1 BEFORE updating depth.
			if !startedInBC && depth == 1 {
				if m := scalaDef.FindStringSubmatch(trimmed); m != nil {
					name := m[1]
					if !isScalaKeyword(name) {
						cur.defs = append(cur.defs, name)
					}
				}
			}
			depth += scalaNetBraces(raw, &bcDepth)
			if depth <= 0 {
				closeBlock(lineNo)
				depth = 0
			}
			continue
		}

		// Top level.
		if startedInBC {
			scalaNetBraces(raw, &bcDepth)
			continue
		}
		if scalaComment.MatchString(raw) {
			continue
		}
		if scalaImport.MatchString(raw) {
			continue
		}
		if scalaAnnotation.MatchString(raw) {
			continue
		}

		if m := scalaTopBlock.FindStringSubmatch(trimmed); m != nil {
			kind := strings.TrimSpace(m[1])
			b := &scalaBlock{kind: kind, name: m[2], startLine: lineNo}
			d := scalaNetBraces(raw, &bcDepth)
			if d > 0 {
				cur = b
				depth = d
			} else {
				// Split header (extends/with clause on next lines); wait for "{".
				pendingBlock = b
			}
			continue
		}
	}
	// Flush any pending block that never got an opening "{" (body-less declaration).
	if pendingBlock != nil {
		pendingBlock.endLine = len(lines)
		blocks = append(blocks, pendingBlock)
		pendingBlock = nil
	}
	closeBlock(len(lines))

	if len(blocks) == 0 {
		return digest.FileMap{}, false
	}

	var entries []digest.MapEntry
	var symbols []string
	for _, b := range blocks {
		label := scalaBlockLabel(b)
		if len(symbols) < 40 {
			symbols = append(symbols, b.kind+" "+b.name)
		}
		entries = append(entries, digest.MapEntry{
			Lines: lineRange(b.startLine, b.endLine),
			Kind:  label,
		})
	}

	return digest.FileMap{
		Summary: scalaSummary(blocks, generated),
		Map:     entries,
		Symbols: symbols,
	}, true
}

// scalaNetBraces counts net brace depth for a Scala line, ignoring braces
// inside double-quoted strings, // comments, and /* */ block comments.
// bcDepth carries block-comment depth across lines.
func scalaNetBraces(line string, bcDepth *int) int {
	depth := 0
	inStr := false
	for i := 0; i < len(line); i++ {
		ch := line[i]
		if *bcDepth > 0 {
			if ch == '*' && i+1 < len(line) && line[i+1] == '/' {
				*bcDepth--
				i++
			}
			continue
		}
		if inStr {
			if ch == '\\' {
				i++
				continue
			}
			if ch == '"' {
				inStr = false
			}
			continue
		}
		switch ch {
		case '"':
			inStr = true
		case '/':
			if i+1 < len(line) && line[i+1] == '/' {
				return depth
			}
			if i+1 < len(line) && line[i+1] == '*' {
				*bcDepth = 1
				i++
			}
		case '{':
			depth++
		case '}':
			depth--
		}
	}
	return depth
}

// isScalaKeyword filters false positives from scalaDef.
func isScalaKeyword(s string) bool {
	switch s {
	case "if", "else", "for", "while", "do", "match", "case", "return",
		"try", "catch", "throw", "new", "class", "object", "trait", "enum",
		"val", "var", "def", "type", "import", "package", "extends", "with",
		"override", "abstract", "sealed", "final", "implicit", "lazy",
		"this", "super", "null", "true", "false", "yield", "given", "using",
		"inline", "transparent", "opaque":
		return true
	}
	return false
}

// scalaBlockLabel builds the Kind label for a Scala block entry.
func scalaBlockLabel(b *scalaBlock) string {
	label := b.kind + " " + b.name
	if len(b.defs) == 0 {
		return label
	}
	displayed := b.defs
	suffix := ""
	if len(displayed) > 4 {
		displayed = displayed[:4]
		suffix = fmt.Sprintf(" (+%d)", len(b.defs)-4)
	}
	return label + " — " + strings.Join(displayed, ", ") + suffix
}

// scalaSummary builds the top-level summary line.
func scalaSummary(blocks []*scalaBlock, generated bool) string {
	counts := map[string]int{}
	defCount := 0
	for _, b := range blocks {
		counts[b.kind]++
		defCount += len(b.defs)
	}

	ordered := []string{
		"class", "abstract class", "sealed class", "final class",
		"case class", "open class",
		"object", "case object",
		"trait", "sealed trait", "open trait",
		"enum", "sealed enum",
	}
	var parts []string
	for _, k := range ordered {
		n := counts[k]
		if n == 0 {
			continue
		}
		if n == 1 {
			parts = append(parts, "1 "+k)
		} else {
			words := strings.Fields(k)
			words[len(words)-1] += "s"
			parts = append(parts, fmt.Sprintf("%d %s", n, strings.Join(words, " ")))
		}
	}
	if defCount == 1 {
		parts = append(parts, "1 def")
	} else if defCount > 1 {
		parts = append(parts, fmt.Sprintf("%d defs", defCount))
	}

	summary := "Scala — " + strings.Join(parts, ", ")
	if generated {
		summary += " — generated, do not edit directly"
	}
	return summary
}

// hasScalaStructure returns true when at least one class/object/trait/enum
// declaration is present.
func hasScalaStructure(lines []string) bool {
	for _, l := range lines {
		if scalaTopBlock.MatchString(l) {
			return true
		}
	}
	return false
}
