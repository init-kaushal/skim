package filemap

import (
	"fmt"
	"path/filepath"
	"regexp"
	"strings"

	"github.com/kaushal/skim/internal/digest"
)

var (
	// rFuncAssign matches top-level R function assignments:
	//   name <- function(...)   name = function(...)
	// Groups: (1) function name.
	rFuncAssign = regexp.MustCompile(
		`^\s*([a-zA-Z.][a-zA-Z0-9._]*)\s*(?:<-|=)\s*function\s*\(`)

	// rSetClass matches S4 class declarations: setClass("Name", ...).
	// Groups: (1) class name.
	rSetClass = regexp.MustCompile(
		`^\s*setClass\s*\(\s*["']([A-Za-z.][A-Za-z0-9._]*)`)

	// rSetGeneric matches S4 generic declarations: setGeneric("name", ...).
	// Groups: (1) generic name.
	rSetGeneric = regexp.MustCompile(
		`^\s*setGeneric\s*\(\s*["']([a-zA-Z.][a-zA-Z0-9._]*)`)

	// rR6Class matches R6 / reference class assignments:
	//   Name <- R6Class("Name", ...)
	//   Name <- setRefClass("Name", ...)
	// Groups: (1) variable name (used as the class name).
	rR6Class = regexp.MustCompile(
		`^\s*([A-Za-z.][A-Za-z0-9._]*)\s*<-\s*(?:R6Class|setRefClass)\s*\(`)

	rGenerated = regexp.MustCompile(`DO NOT EDIT|auto.?generated|This file was (automatically )?generated|Generated by|@generated`)
)

// parseRFile builds a FileMap for an R source file. R has no formal module
// structure, so the entire file maps to one entry; the Kind label lists up to
// 4 class and function names with +N overflow.
//
// Depth tracking uses combined brace ({}) plus paren (()) depth. This ensures
// that functions defined as named arguments inside a call — e.g.
// list(callback = function(x) ...) — are at depth > 0 and not captured.
func parseRFile(src, filePath string) (digest.FileMap, bool) {
	lines := splitLines(src)
	if len(lines) == 0 {
		return digest.FileMap{}, false
	}
	if !hasRStructure(lines) {
		return digest.FileMap{}, false
	}

	generated := false
	for _, l := range lines[:min(len(lines), 10)] {
		if rGenerated.MatchString(l) {
			generated = true
			break
		}
	}

	base := filepath.Base(filePath)
	stem := strings.TrimSuffix(base, filepath.Ext(base))

	var classes []string // S4/R6/R5 class names
	var fns []string     // function and generic names
	seenClasses := make(map[string]bool)
	seenFns := make(map[string]bool)

	depth := 0
	// Persistent string-mode flags: R allows multiline strings.
	inDouble := false
	inSingle := false
	inBacktick := false

	for _, raw := range lines {
		trimmed := strings.TrimSpace(raw)
		if trimmed == "" {
			continue
		}

		// Collect at depth 0 BEFORE updating depth (depth-before-update rule).
		if depth == 0 {
			if m := rSetClass.FindStringSubmatch(trimmed); m != nil {
				name := m[1]
				if !seenClasses[name] {
					classes = append(classes, name)
					seenClasses[name] = true
				}
			} else if m := rR6Class.FindStringSubmatch(trimmed); m != nil {
				name := m[1]
				if !isRKeyword(name) && !seenClasses[name] {
					classes = append(classes, name)
					seenClasses[name] = true
				}
			} else if m := rSetGeneric.FindStringSubmatch(trimmed); m != nil {
				name := m[1]
				if !isRKeyword(name) && !seenFns[name] {
					fns = append(fns, name)
					seenFns[name] = true
				}
			} else if m := rFuncAssign.FindStringSubmatch(trimmed); m != nil {
				name := m[1]
				if !isRKeyword(name) && !seenFns[name] {
					fns = append(fns, name)
					seenFns[name] = true
				}
			}
		}

		depth += rNetDepth(raw, &inDouble, &inSingle, &inBacktick)
		if depth < 0 {
			depth = 0
		}
	}

	if len(classes) == 0 && len(fns) == 0 {
		return digest.FileMap{}, false
	}

	combined := append(classes, fns...)
	label := rLabel(stem, combined)
	summary := rSummary(stem, len(classes), len(fns), generated)

	var symbols []string
	for _, c := range classes {
		symbols = append(symbols, "class "+c)
	}
	for _, f := range fns {
		symbols = append(symbols, "fn "+f)
	}

	return digest.FileMap{
		Summary: summary,
		Map: []digest.MapEntry{{
			Lines: lineRange(1, len(lines)),
			Kind:  label,
		}},
		Symbols: symbols,
	}, true
}

// rNetDepth counts the net combined brace-and-paren depth change for a
// single R line. Brace depth ({}) tracks function/control-flow bodies; paren
// depth (()) tracks function-call argument lists. Combining them means that
// a function definition appearing as a named argument — list(f = function()
// ...) — is correctly seen as being at depth > 0.
//
// String content ("…", '…', `…`) and # comments are skipped.
// inDouble, inSingle, inBacktick persist across calls for multiline strings.
func rNetDepth(line string, inDouble, inSingle, inBacktick *bool) int {
	depth := 0
	for i := 0; i < len(line); i++ {
		ch := line[i]

		if *inDouble {
			if ch == '\\' {
				i++
				continue
			}
			if ch == '"' {
				*inDouble = false
			}
			continue
		}
		if *inSingle {
			if ch == '\\' {
				i++
				continue
			}
			if ch == '\'' {
				*inSingle = false
			}
			continue
		}
		if *inBacktick {
			if ch == '`' {
				*inBacktick = false
			}
			continue
		}

		switch ch {
		case '#':
			return depth // rest of line is a comment
		case '"':
			*inDouble = true
		case '\'':
			*inSingle = true
		case '`':
			*inBacktick = true
		case '{', '(':
			depth++
		case '}', ')':
			depth--
		}
	}
	return depth
}

func isRKeyword(s string) bool {
	switch s {
	case "if", "else", "for", "while", "repeat", "break", "next", "return",
		"function", "TRUE", "FALSE", "NULL", "Inf", "NaN", "NA",
		"NA_integer_", "NA_real_", "NA_complex_", "NA_character_",
		"in":
		return true
	}
	return false
}

func rLabel(stem string, names []string) string {
	label := "module " + stem
	if len(names) == 0 {
		return label
	}
	displayed := names
	suffix := ""
	if len(displayed) > 4 {
		displayed = displayed[:4]
		suffix = fmt.Sprintf(" (+%d)", len(names)-4)
	}
	return label + " — " + strings.Join(displayed, ", ") + suffix
}

func rSummary(stem string, classCount, fnCount int, generated bool) string {
	s := "R — " + stem
	var parts []string
	if classCount == 1 {
		parts = append(parts, "1 class")
	} else if classCount > 1 {
		parts = append(parts, fmt.Sprintf("%d classes", classCount))
	}
	if fnCount == 1 {
		parts = append(parts, "1 function")
	} else if fnCount > 1 {
		parts = append(parts, fmt.Sprintf("%d functions", fnCount))
	}
	if len(parts) > 0 {
		s += ", " + strings.Join(parts, ", ")
	}
	if generated {
		s += " — generated, do not edit directly"
	}
	return s
}

func hasRStructure(lines []string) bool {
	for _, l := range lines {
		if rFuncAssign.MatchString(l) ||
			rSetClass.MatchString(l) ||
			rR6Class.MatchString(l) {
			return true
		}
	}
	return false
}
