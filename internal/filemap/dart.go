package filemap

import (
	"fmt"
	"regexp"
	"strings"

	"github.com/kaushal/skim/internal/digest"
)

var (
	// dartTopBlock matches a Dart type declaration.
	// Dart 3 class modifiers (abstract, final, base, interface, sealed) and
	// mixin are listed only in group 1 so they appear in the kind label.
	// Groups: (1) kind phrase, (2) name.
	dartTopBlock = regexp.MustCompile(
		`^\s*(?:(?:@\w+(?:\([^)]*\))?\s+)*)` + // optional annotations
			`((?:(?:abstract|final|base|interface|sealed|mixin)\s+)*` + // qualifiers in group 1
			`(?:class|mixin|enum))\s+` + // primary keyword in group 1 (extension handled separately)
			`([A-Za-z_$][A-Za-z0-9_$]*)`) // name in group 2

	// dartExtension matches both named and unnamed Dart extension declarations.
	// Dart supports both:   extension StringX on String { ... }
	//                  and: extension on String { ... }
	// The name group is optional; when the engine tries to match a name and then
	// can't find the "on" keyword, it backtracks and treats the token as the type.
	// Groups: (1) name (empty for unnamed extensions), (2) on-type (trimmed).
	dartExtension = regexp.MustCompile(
		`^\s*extension\s+` +
			`(?:([A-Za-z_$][A-Za-z0-9_$]*)\s+)?` + // optional name in group 1
			`on\s+([^{;\n]+)`) // on-type in group 2 (trimmed by caller)

	// dartMethod matches a Dart method declaration at depth 1.
	// Requires at least one return-type word before the name so control-flow
	// keywords (if, for, while) are rejected: they need a `(` immediately after
	// the keyword with no space+identifier in between.
	// Groups: (1) name.
	dartMethod = regexp.MustCompile(
		`^\s*(?:(?:@\w+(?:\([^)]*\))?\s+)*)` + // optional annotations
			`(?:(?:static|abstract|external|override|covariant|late|const|final|factory|async)\s+)*` + // modifiers
			// One or more return-type words; the generic pattern handles one level of nesting
			// (e.g. Future<Map<String, dynamic>>) by allowing <…> inside the outer angle brackets.
			`(?:[A-Za-z_$][\w$]*(?:<[^<>]*(?:<[^<>]*>[^<>]*)*>)?(?:\?|!)?\s+)+` +
			`(?:set\s+)?` + // optional set keyword (setters: "set value(v)" — 'set' consumed as return type)
			`([A-Za-z_$][A-Za-z0-9_$]*)` + // name
			`\s*\(`) // opening paren

	// dartGetter matches a Dart getter declaration at depth 1.
	// Getters have an explicit return type, the "get" keyword, a name, and NO
	// opening paren — so dartMethod (which requires "(") never captures them.
	// Groups: (1) name.
	dartGetter = regexp.MustCompile(
		`^\s*(?:(?:@\w+(?:\([^)]*\))?\s+)*)` + // optional annotations
			`(?:(?:static|abstract|external|override|covariant|late|const|final)\s+)*` +
			`(?:[A-Za-z_$][\w$]*(?:<[^<>]*(?:<[^<>]*>[^<>]*)*>)?(?:\?|!)?\s+)+` + // return type
			`get\s+` + // 'get' keyword distinguishes from field declarations
			`([A-Za-z_$][A-Za-z0-9_$]*)`) // name

	dartLineComment = regexp.MustCompile(`^\s*(?:///|//)`)
	dartImport      = regexp.MustCompile(`^\s*(?:import|export|library|part)\s`)
	dartAnnotation  = regexp.MustCompile(`^\s*@`)
	dartGenerated   = regexp.MustCompile(`DO NOT EDIT|auto.?generated|This file was (automatically )?generated|Generated by|@generated|generated code`)
)

type dartBlock struct {
	kind      string
	name      string
	startLine int
	endLine   int
	methods   []string
}

// parseDartFile builds a FileMap from a Dart source file. Each top-level type
// declaration (class, mixin, enum, extension) becomes one map entry; the Kind
// label lists up to 4 method names with +N overflow.
func parseDartFile(src, _ string) (digest.FileMap, bool) {
	lines := splitLines(src)
	if len(lines) == 0 {
		return digest.FileMap{}, false
	}
	if !hasDartStructure(lines) {
		return digest.FileMap{}, false
	}

	generated := false
	for _, l := range lines[:min(len(lines), 10)] {
		if dartGenerated.MatchString(l) {
			generated = true
			break
		}
	}

	var blocks []*dartBlock
	var cur *dartBlock
	var pendingBlock *dartBlock
	depth := 0
	bcDepth := 0
	inDouble := false // persistent: true while inside a multi-line double-quoted string
	inSingle := false // persistent: true while inside a multi-line single-quoted string

	closeBlock := func(endLine int) {
		if cur != nil {
			cur.endLine = endLine
			blocks = append(blocks, cur)
			cur = nil
		}
	}

	for i, raw := range lines {
		lineNo := i + 1
		trimmed := strings.TrimSpace(raw)

		if trimmed == "" {
			continue
		}

		startedInBC := bcDepth > 0

		if pendingBlock != nil {
			d := dartNetBraces(raw, &bcDepth, &inDouble, &inSingle)
			if d > 0 {
				cur = pendingBlock
				depth = d
				pendingBlock = nil
			} else if d < 0 {
				pendingBlock = nil
			}
			continue
		}

		if cur != nil {
			if !startedInBC && !inDouble && !inSingle && depth == 1 {
				if m := dartMethod.FindStringSubmatch(trimmed); m != nil {
					if name := m[1]; isDartMemberName(name) {
						cur.methods = append(cur.methods, name)
					}
				} else if m := dartGetter.FindStringSubmatch(trimmed); m != nil {
					if name := m[1]; isDartMemberName(name) {
						cur.methods = append(cur.methods, name)
					}
				}
			}
			depth += dartNetBraces(raw, &bcDepth, &inDouble, &inSingle)
			if depth <= 0 {
				closeBlock(lineNo)
				depth = 0
			}
			continue
		}

		// Top level.
		if startedInBC || inDouble || inSingle {
			dartNetBraces(raw, &bcDepth, &inDouble, &inSingle)
			continue
		}
		if dartLineComment.MatchString(raw) {
			continue
		}
		if dartImport.MatchString(raw) {
			continue
		}
		if dartAnnotation.MatchString(raw) {
			continue
		}

		if m := dartTopBlock.FindStringSubmatch(trimmed); m != nil {
			kind := strings.TrimSpace(m[1])
			b := &dartBlock{kind: kind, name: m[2], startLine: lineNo}
			d := dartNetBraces(raw, &bcDepth, &inDouble, &inSingle)
			if d > 0 {
				cur = b
				depth = d
			} else if !strings.Contains(trimmed, ";") {
				// Multi-line header (extends/with/implements on next lines).
				pendingBlock = b
			}
			continue
		}

		if m := dartExtension.FindStringSubmatch(trimmed); m != nil {
			name := strings.TrimSpace(m[1])
			if name == "" {
				// Unnamed extension: label as "on TypeName".
				name = "on " + strings.TrimSpace(m[2])
			}
			b := &dartBlock{kind: "extension", name: name, startLine: lineNo}
			d := dartNetBraces(raw, &bcDepth, &inDouble, &inSingle)
			if d > 0 {
				cur = b
				depth = d
			} else if !strings.Contains(trimmed, ";") {
				pendingBlock = b
			}
			continue
		}

		dartNetBraces(raw, &bcDepth, &inDouble, &inSingle)
	}
	closeBlock(len(lines))

	if len(blocks) == 0 {
		return digest.FileMap{}, false
	}

	var entries []digest.MapEntry
	var symbols []string
	for _, b := range blocks {
		label := dartBlockLabel(b)
		if len(symbols) < 40 {
			symbols = append(symbols, b.kind+" "+b.name)
		}
		entries = append(entries, digest.MapEntry{
			Lines: lineRange(b.startLine, b.endLine),
			Kind:  label,
		})
	}

	return digest.FileMap{
		Summary: dartSummary(blocks, generated),
		Map:     entries,
		Symbols: symbols,
	}, true
}

// dartNetBraces counts net brace depth for a Dart line, ignoring braces inside
// double-quoted strings, single-quoted strings, // and /// comments, and
// /* */ block comments. inDouble and inSingle are persistent across calls.
//
// Triple-quoted strings (""" and ''') are handled naturally: three consecutive
// quote characters toggle the persistent string state three times — from false
// to true, true to false, false to true — so at the end of the triple opener
// the state is true (open), and the matching triple closer returns it to false.
// Braces in between are correctly skipped.
func dartNetBraces(line string, bcDepth *int, inDouble *bool, inSingle *bool) int {
	depth := 0
	for i := 0; i < len(line); i++ {
		ch := line[i]
		if *bcDepth > 0 {
			if ch == '*' && i+1 < len(line) && line[i+1] == '/' {
				*bcDepth--
				i++
			}
			continue
		}
		if *inDouble {
			if ch == '\\' {
				i++
				continue
			}
			if ch == '"' {
				*inDouble = false
			}
			continue
		}
		if *inSingle {
			if ch == '\\' {
				i++
				continue
			}
			if ch == '\'' {
				*inSingle = false
			}
			continue
		}
		switch ch {
		case '"':
			*inDouble = true
		case '\'':
			*inSingle = true
		case '/':
			if i+1 < len(line) && line[i+1] == '/' {
				return depth
			}
			if i+1 < len(line) && line[i+1] == '*' {
				*bcDepth = 1
				i++
			}
		case '{':
			depth++
		case '}':
			depth--
		}
	}
	return depth
}

func isDartKeyword(s string) bool {
	switch s {
	case "if", "else", "for", "while", "do", "switch", "case", "break",
		"continue", "return", "new", "throw", "try", "catch", "finally",
		"assert", "await", "yield", "in", "is", "as", "var", "final",
		"const", "late", "static", "class", "mixin", "enum", "extension",
		"typedef", "import", "export", "library", "part", "show", "hide",
		"abstract", "sealed", "base", "interface", "override", "covariant",
		"external", "factory", "this", "super", "null", "true", "false",
		"implements", "extends", "with", "on", "required", "dynamic",
		"Function": // built-in type used in function-type syntax, not a valid method name
		return true
	}
	return false
}

// isDartMemberName returns true when name is a valid Dart member name to collect.
// Dart methods and getters are always camelCase (lowercase or '_'/'$' first);
// constructor names start with UpperCase and are false positives caused by
// modifier backtracking: "const User(...)" → modifier group matches 0 times,
// "const" becomes the return type, "User" becomes the name. Filter them out.
func isDartMemberName(name string) bool {
	if len(name) == 0 || isDartKeyword(name) {
		return false
	}
	first := name[0]
	return first == '_' || first == '$' || (first >= 'a' && first <= 'z')
}

func dartBlockLabel(b *dartBlock) string {
	label := b.kind + " " + b.name
	if len(b.methods) == 0 {
		return label
	}
	displayed := b.methods
	suffix := ""
	if len(displayed) > 4 {
		displayed = displayed[:4]
		suffix = fmt.Sprintf(" (+%d)", len(b.methods)-4)
	}
	return label + " — " + strings.Join(displayed, ", ") + suffix
}

func dartSummary(blocks []*dartBlock, generated bool) string {
	counts := map[string]int{}
	methodCount := 0
	for _, b := range blocks {
		counts[b.kind]++
		methodCount += len(b.methods)
	}

	ordered := []string{
		"class", "abstract class", "final class", "base class",
		"interface class", "sealed class",
		"abstract interface class", "abstract base class",
		"mixin", "mixin class",
		"enum",
		"extension",
	}
	var parts []string
	for _, k := range ordered {
		n := counts[k]
		if n == 0 {
			continue
		}
		if n == 1 {
			parts = append(parts, "1 "+k)
		} else {
			words := strings.Fields(k)
			switch words[len(words)-1] {
			case "class":
				words[len(words)-1] = "classes"
			case "mixin":
				words[len(words)-1] = "mixins"
			case "enum":
				words[len(words)-1] = "enums"
			case "extension":
				words[len(words)-1] = "extensions"
			default:
				words[len(words)-1] += "s"
			}
			parts = append(parts, fmt.Sprintf("%d %s", n, strings.Join(words, " ")))
		}
	}
	if methodCount == 1 {
		parts = append(parts, "1 method")
	} else if methodCount > 1 {
		parts = append(parts, fmt.Sprintf("%d methods", methodCount))
	}

	summary := "Dart — " + strings.Join(parts, ", ")
	if generated {
		summary += " — generated, do not edit directly"
	}
	return summary
}

func hasDartStructure(lines []string) bool {
	for _, l := range lines {
		if dartTopBlock.MatchString(l) || dartExtension.MatchString(l) {
			return true
		}
	}
	return false
}
