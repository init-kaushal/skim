package filemap

import (
	"fmt"
	"path/filepath"
	"regexp"
	"strings"

	"github.com/kaushal/skim/internal/digest"
)

var (
	// fsharpModule matches module declarations at the top of an F# file.
	// Handles both simple (module MyModule) and dotted (module MyApp.Core).
	// Groups: (1) module name.
	fsharpModule = regexp.MustCompile(
		`^module\s+((?:[A-Za-z][A-Za-z0-9_]*\.)*[A-Za-z][A-Za-z0-9_]*)`)

	// fsharpNamespace matches namespace declarations.
	// Groups: (1) namespace name.
	fsharpNamespace = regexp.MustCompile(
		`^namespace\s+((?:[A-Za-z][A-Za-z0-9_]*\.)*[A-Za-z][A-Za-z0-9_]*)`)

	// fsharpLet matches let / let rec / let inline bindings, with optional
	// access modifiers (private, internal, public) and mutability.
	// Captures meaningful names only; _ and () fall through.
	// Groups: (1) binding name.
	fsharpLet = regexp.MustCompile(
		`^let(?:\s+(?:rec|inline|private|internal|public|mutable))*\s+([a-z_][A-Za-z0-9_']*)`)

	// fsharpType matches type declarations: records, discriminated unions,
	// classes, interfaces, aliases. Handles optional access modifiers and a
	// single quote-prefixed type parameter (type 'a option = ...).
	// Groups: (1) type name.
	fsharpType = regexp.MustCompile(
		`^type\s+(?:private\s+|internal\s+|public\s+)?(?:'[a-z_][A-Za-z0-9_']*\s+)*([A-Za-z_][A-Za-z0-9_']*)`)

	// fsharpVal matches val declarations in .fsi signature files.
	// Groups: (1) value name.
	fsharpVal = regexp.MustCompile(`^val\s+([a-z_][A-Za-z0-9_']*)`)

	fsharpGenerated = regexp.MustCompile(
		`DO NOT EDIT|auto.?generated|This file was (automatically )?generated|Generated by|@generated`)
)

// parseFSharpFile builds a FileMap for an F# source (.fs), script (.fsx), or
// signature (.fsi) file. F# uses significant indentation; top-level
// declarations always start at column 0 in the common implicit-module form.
//
// Block comments (* ... *) are nestable and tracked with a depth counter.
// Line comments (//) terminate keyword scanning for the rest of a line.
//
// .fs/.fsx: collects module, namespace, type, let/let rec.
// .fsi:     collects module, type, val signatures.
//
// The entire file maps to one entry; the module or namespace name (if found)
// replaces the file stem as the label prefix. Types appear first in the Kind
// label, followed by function names, up to 4 with +N overflow.
func parseFSharpFile(src, filePath string) (digest.FileMap, bool) {
	lines := splitLines(src)
	if len(lines) == 0 {
		return digest.FileMap{}, false
	}
	if !hasFSharpStructure(lines) {
		return digest.FileMap{}, false
	}

	ext := strings.ToLower(filepath.Ext(filePath))
	isSignature := ext == ".fsi"

	generated := false
	for _, l := range lines[:min(len(lines), 10)] {
		if fsharpGenerated.MatchString(l) {
			generated = true
			break
		}
	}

	var moduleName string // from 'module Name' or 'namespace Name'
	var structural []string
	var defs []string
	seenStructural := make(map[string]bool)
	seenDefs := make(map[string]bool)
	commentDepth := 0

	for _, raw := range lines {
		trimmed := strings.TrimSpace(raw)
		if trimmed == "" {
			continue
		}

		// Nestable (* ... *) block comments — same semantics as OCaml.
		depthAtStart := commentDepth
		commentDepth = updateFSharpBlockCommentDepth(raw, commentDepth)
		if depthAtStart > 0 {
			continue
		}

		// Skip lines that are indented (inside type bodies, function bodies,
		// or explicit module blocks). Top-level declarations start at column 0.
		if len(raw) > 0 && (raw[0] == ' ' || raw[0] == '\t') {
			continue
		}

		// Skip lines that begin a block comment or a line comment.
		if strings.HasPrefix(trimmed, "(*") || strings.HasPrefix(trimmed, "//") {
			continue
		}

		// Module declaration: use as the label identifier.
		if m := fsharpModule.FindStringSubmatch(trimmed); m != nil {
			if moduleName == "" {
				moduleName = m[1]
			}
			continue
		}

		// Namespace declaration: use as the label identifier when no module found.
		if m := fsharpNamespace.FindStringSubmatch(trimmed); m != nil {
			if moduleName == "" {
				moduleName = m[1]
			}
			continue
		}

		// Type declarations.
		if m := fsharpType.FindStringSubmatch(trimmed); m != nil {
			name := m[1]
			if !isFSharpKeyword(name) && !seenStructural[name] {
				structural = append(structural, name)
				seenStructural[name] = true
			}
			continue
		}

		if isSignature {
			// .fsi: val declarations are the function signatures.
			if m := fsharpVal.FindStringSubmatch(trimmed); m != nil {
				name := m[1]
				if name != "_" && !isFSharpKeyword(name) && !seenDefs[name] {
					defs = append(defs, name)
					seenDefs[name] = true
				}
			}
		} else {
			// .fs/.fsx: let bindings.
			if m := fsharpLet.FindStringSubmatch(trimmed); m != nil {
				name := m[1]
				if name != "_" && !isFSharpKeyword(name) && !seenDefs[name] {
					defs = append(defs, name)
					seenDefs[name] = true
				}
			}
		}
	}

	if moduleName == "" && len(structural) == 0 && len(defs) == 0 {
		return digest.FileMap{}, false
	}

	base := filepath.Base(filePath)
	stem := strings.TrimSuffix(base, filepath.Ext(base))

	labelBase := stem
	if moduleName != "" {
		labelBase = moduleName
	}

	combined := append(structural, defs...)
	label := fsharpLabel(labelBase, combined)
	summary := fsharpSummary(labelBase, len(structural), len(defs), isSignature, generated)

	var symbols []string
	for _, s := range structural {
		symbols = append(symbols, "type "+s)
	}
	for _, d := range defs {
		if isSignature {
			symbols = append(symbols, "val "+d)
		} else {
			symbols = append(symbols, "fn "+d)
		}
	}

	return digest.FileMap{
		Summary: summary,
		Map: []digest.MapEntry{{
			Lines: lineRange(1, len(lines)),
			Kind:  label,
		}},
		Symbols: symbols,
	}, true
}

// updateFSharpBlockCommentDepth scans line and returns the updated (* *)
// nesting depth. F# block comments are nestable (a boolean exits too early
// on the inner *) of (* (* inner *) still outer *)).
// // line comments are honoured: (* after // is not a real comment opener.
func updateFSharpBlockCommentDepth(line string, depth int) int {
	for i := 0; i < len(line); i++ {
		ch := line[i]
		next := byte(0)
		if i+1 < len(line) {
			next = line[i+1]
		}
		if depth > 0 {
			if ch == '(' && next == '*' {
				depth++
				i++
			} else if ch == '*' && next == ')' {
				depth--
				i++
			}
		} else {
			if ch == '/' && next == '/' {
				break // line comment — stop scanning
			}
			if ch == '(' && next == '*' {
				depth++
				i++
			}
		}
	}
	return depth
}

func isFSharpKeyword(s string) bool {
	switch s {
	case "rec", "inline", "mutable", "private", "internal", "public",
		"abstract", "override", "virtual", "default", "static",
		"member", "new", "base", "and", "with", "do",
		"if", "then", "else", "match", "when",
		"open", "use", "try", "raise", "for", "while",
		"true", "false", "null", "not", "global", "_":
		return true
	}
	return false
}

func hasFSharpStructure(lines []string) bool {
	for _, l := range lines {
		trimmed := strings.TrimSpace(l)
		if fsharpModule.MatchString(trimmed) ||
			fsharpNamespace.MatchString(trimmed) ||
			fsharpLet.MatchString(trimmed) ||
			fsharpType.MatchString(trimmed) ||
			fsharpVal.MatchString(trimmed) {
			return true
		}
	}
	return false
}

func fsharpLabel(labelBase string, names []string) string {
	label := "module " + labelBase
	if len(names) == 0 {
		return label
	}
	displayed := names
	suffix := ""
	if len(displayed) > 4 {
		displayed = displayed[:4]
		suffix = fmt.Sprintf(" (+%d)", len(names)-4)
	}
	return label + " — " + strings.Join(displayed, ", ") + suffix
}

func fsharpSummary(labelBase string, structuralCount, defCount int, isSignature, generated bool) string {
	lang := "F#"
	if isSignature {
		lang = "F# signature"
	}
	s := lang + " — " + labelBase
	var parts []string
	if structuralCount == 1 {
		parts = append(parts, "1 type")
	} else if structuralCount > 1 {
		parts = append(parts, fmt.Sprintf("%d types", structuralCount))
	}
	defLabel := "function"
	if isSignature {
		defLabel = "val"
	}
	if defCount == 1 {
		parts = append(parts, "1 "+defLabel)
	} else if defCount > 1 {
		parts = append(parts, fmt.Sprintf("%d %ss", defCount, defLabel))
	}
	if len(parts) > 0 {
		s += ", " + strings.Join(parts, ", ")
	}
	if generated {
		s += " — generated, do not edit directly"
	}
	return s
}
