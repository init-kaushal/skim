package filemap

import (
	"fmt"
	"path/filepath"
	"regexp"
	"strings"

	"github.com/kaushal/skim/internal/digest"
)

var (
	// luaFuncDecl matches named function declarations:
	//   function name(...)        local function name(...)
	//   function M.name(...)      function M:name(...)
	// Groups: (1) full dotted/colon-qualified name.
	luaFuncDecl = regexp.MustCompile(
		`^\s*(?:local\s+)?function\s+([A-Za-z_][A-Za-z0-9_.:]*)\s*\(`)

	// luaFuncAssign matches assignment-form function definitions:
	//   name = function(...)      local name = function(...)
	//   M.name = function(...)
	// Groups: (1) dotted name.
	luaFuncAssign = regexp.MustCompile(
		`^\s*(?:local\s+)?([A-Za-z_][A-Za-z0-9_.]*)\s*=\s*function\s*\(`)

	luaGenerated = regexp.MustCompile(`DO NOT EDIT|auto.?generated|This file was (automatically )?generated|Generated by|@generated`)
)

// parseLuaFile builds a FileMap for a Lua source file. Lua has no formal
// module declaration, so the entire file is one map entry; the Kind label
// lists up to 4 top-level function names with +N overflow.
func parseLuaFile(src, filePath string) (digest.FileMap, bool) {
	lines := splitLines(src)
	if len(lines) == 0 {
		return digest.FileMap{}, false
	}
	if !hasLuaStructure(lines) {
		return digest.FileMap{}, false
	}

	generated := false
	for _, l := range lines[:min(len(lines), 10)] {
		if luaGenerated.MatchString(l) {
			generated = true
			break
		}
	}

	// Use the file's stem as the module name (require 'stem' convention).
	base := filepath.Base(filePath)
	stem := strings.TrimSuffix(base, filepath.Ext(base))

	var fns []string
	seen := make(map[string]bool)
	depth := 0
	// longBracket: -1 = not inside a long bracket; ≥0 = inside level-N bracket.
	// doSkip: count of pending for/while headers that have not yet seen their "do".
	// Both persist across lines so multiline headers like "for …\ndo" work correctly.
	longBracket := -1
	doSkip := 0

	for _, raw := range lines {
		trimmed := strings.TrimSpace(raw)
		if trimmed == "" {
			continue
		}

		// Snapshot before scanning: skip function detection while inside a long block.
		wasInLong := longBracket >= 0

		// Collect top-level function names BEFORE updating depth so that
		// `function foo()` at the current depth 0 is captured before the
		// `function` keyword pushes depth to 1.
		if depth == 0 && !wasInLong {
			if m := luaFuncDecl.FindStringSubmatch(trimmed); m != nil {
				name := m[1]
				if !isLuaKeyword(name) && !seen[name] {
					fns = append(fns, name)
					seen[name] = true
				}
			} else if m := luaFuncAssign.FindStringSubmatch(trimmed); m != nil {
				name := m[1]
				if !isLuaKeyword(name) && !seen[name] {
					fns = append(fns, name)
					seen[name] = true
				}
			}
		}

		depth += luaNetBlocks(raw, &longBracket, &doSkip)
		if depth < 0 {
			depth = 0
		}
	}

	if len(fns) == 0 {
		return digest.FileMap{}, false
	}

	label := luaLabel(stem, fns)
	summary := luaSummary(stem, len(fns), generated)

	return digest.FileMap{
		Summary: summary,
		Map: []digest.MapEntry{{
			Lines: lineRange(1, len(lines)),
			Kind:  label,
		}},
		Symbols: []string{"module " + stem},
	}, true
}

// luaNetBlocks counts the net block depth change for a single Lua line.
//
// Opens (+1): function, if, for, while, repeat, { and standalone do.
// Closes (-1): end, until, }.
//
// longBracket and doSkip persist across calls (owned by the caller):
//   - longBracket: -1 = not inside a long bracket; ≥0 = inside level-N bracket.
//     Handles all long-bracket forms including [=[ ]=] and [==[ ]==].
//   - doSkip: count of for/while headers whose syntactic "do" has not yet been
//     seen. Persisting this across lines correctly handles multiline headers
//     where "do" appears on the line after "for"/"while".
//
// Content inside "…", '…', long brackets, and --comments is skipped.
func luaNetBlocks(line string, longBracket *int, doSkip *int) int {
	net := 0
	inStr := false
	strChar := byte(0)

	for i := 0; i < len(line); i++ {
		ch := line[i]

		// Inside a long string or comment: scan for the matching close bracket.
		// A level-N long bracket closes with ] followed by N '=' signs then ].
		if *longBracket >= 0 {
			if ch == ']' {
				j := i + 1
				cnt := 0
				for j < len(line) && line[j] == '=' {
					cnt++
					j++
				}
				if cnt == *longBracket && j < len(line) && line[j] == ']' {
					*longBracket = -1
					i = j
				}
			}
			continue
		}

		// Single-line string handling (strings don't span lines in Lua
		// without the long-bracket form, so inStr resets each call).
		if inStr {
			if ch == '\\' {
				i++
				continue
			}
			if ch == strChar {
				inStr = false
			}
			continue
		}

		// Detect -- (line comment) vs --[=*[ (long comment opener).
		if ch == '-' && i+1 < len(line) && line[i+1] == '-' {
			j := i + 2
			if j < len(line) && line[j] == '[' {
				level, end := luaLongBracketLevel(line, j)
				if end >= 0 {
					*longBracket = level
					i = end
					continue
				}
			}
			return net // rest of line is a line comment
		}

		// Long string opener [=*[.
		if ch == '[' {
			level, end := luaLongBracketLevel(line, i)
			if end >= 0 {
				*longBracket = level
				i = end
				continue
			}
			// bare [ — not a long-bracket opener, fall through
		}

		// String opener.
		if ch == '"' || ch == '\'' {
			inStr = true
			strChar = ch
			continue
		}

		// Table constructors contribute to depth so that functions defined
		// inside tables (M = { method = function() end }) are at depth > 0.
		if ch == '{' {
			net++
			continue
		}
		if ch == '}' {
			net--
			continue
		}

		// Word-boundary guard: skip if previous char is an identifier char.
		if i > 0 && isLuaIdChar(line[i-1]) {
			continue
		}

		switch {
		case luaMatchWord(line, i, "function"):
			net++
			i += len("function") - 1
		case luaMatchWord(line, i, "if"):
			net++
			i += len("if") - 1
		case luaMatchWord(line, i, "for"):
			net++
			(*doSkip)++
			i += len("for") - 1
		case luaMatchWord(line, i, "while"):
			net++
			(*doSkip)++
			i += len("while") - 1
		case luaMatchWord(line, i, "repeat"):
			net++
			i += len("repeat") - 1
		case luaMatchWord(line, i, "do"):
			if *doSkip > 0 {
				(*doSkip)-- // syntactic do from for/while header — don't count
			} else {
				net++ // standalone do...end block
			}
			i += len("do") - 1
		case luaMatchWord(line, i, "end"):
			net--
			i += len("end") - 1
		case luaMatchWord(line, i, "until"):
			net--
			i += len("until") - 1
		}
	}
	return net
}

// luaLongBracketLevel checks whether line[pos] starts a long-bracket opener
// of the form [=*[ and returns (level, indexOfClosingBracket).
// Returns (-1, -1) if pos does not start a valid opener.
func luaLongBracketLevel(line string, pos int) (int, int) {
	if pos >= len(line) || line[pos] != '[' {
		return -1, -1
	}
	j := pos + 1
	level := 0
	for j < len(line) && line[j] == '=' {
		level++
		j++
	}
	if j >= len(line) || line[j] != '[' {
		return -1, -1
	}
	return level, j
}

// luaMatchWord returns true when line[pos:] starts with word and the character
// immediately after (if any) is not a Lua identifier character.
func luaMatchWord(line string, pos int, word string) bool {
	end := pos + len(word)
	if end > len(line) {
		return false
	}
	if line[pos:end] != word {
		return false
	}
	if end < len(line) && isLuaIdChar(line[end]) {
		return false
	}
	return true
}

// isLuaIdChar returns true for characters that can appear inside a Lua
// identifier (alphanumeric and underscore; dots and colons are NOT included
// so they act as word boundaries for keyword detection).
func isLuaIdChar(ch byte) bool {
	return ch == '_' ||
		(ch >= 'a' && ch <= 'z') || (ch >= 'A' && ch <= 'Z') || (ch >= '0' && ch <= '9')
}

// isLuaKeyword returns true for Lua reserved words to filter false positives.
func isLuaKeyword(s string) bool {
	switch s {
	case "and", "break", "do", "else", "elseif", "end", "false", "for",
		"function", "goto", "if", "in", "local", "nil", "not", "or",
		"repeat", "return", "then", "true", "until", "while":
		return true
	}
	return false
}

func luaLabel(stem string, fns []string) string {
	label := "module " + stem
	if len(fns) == 0 {
		return label
	}
	displayed := fns
	suffix := ""
	if len(displayed) > 4 {
		displayed = displayed[:4]
		suffix = fmt.Sprintf(" (+%d)", len(fns)-4)
	}
	return label + " — " + strings.Join(displayed, ", ") + suffix
}

func luaSummary(stem string, fnCount int, generated bool) string {
	s := "Lua — " + stem
	if fnCount == 1 {
		s += ", 1 function"
	} else if fnCount > 1 {
		s += fmt.Sprintf(", %d functions", fnCount)
	}
	if generated {
		s += " — generated, do not edit directly"
	}
	return s
}

func hasLuaStructure(lines []string) bool {
	for _, l := range lines {
		if luaFuncDecl.MatchString(l) || luaFuncAssign.MatchString(l) {
			return true
		}
	}
	return false
}
