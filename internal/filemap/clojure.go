package filemap

import (
	"fmt"
	"path/filepath"
	"regexp"
	"strings"

	"github.com/kaushal/skim/internal/digest"
)

// clojureSymbol matches most valid Clojure symbol characters:
// letters, digits, _, *, !, ?, +, <, >, =, ., /, - (the last four must be
// in safe positions for the character class).
const clojureSymbol = `[A-Za-z_*!?+<>=./-][A-Za-z0-9_*!?+<>=./-]*`

var (
	// clojureNS matches namespace declarations: (ns my.namespace ...).
	// Groups: (1) namespace name.
	clojureNS = regexp.MustCompile(`^\(ns\s+(` + clojureSymbol + `)`)

	// clojureDefn matches function definitions: (defn name ...) / (defn- name ...).
	// defn- is the private-function convention.
	// Groups: (1) function name.
	clojureDefn = regexp.MustCompile(`^\(defn-?\s+(` + clojureSymbol + `)`)

	// clojureDefmacro matches macro definitions.
	// Groups: (1) macro name.
	clojureDefmacro = regexp.MustCompile(`^\(defmacro\s+(` + clojureSymbol + `)`)

	// clojureDefprotocol matches protocol declarations.
	// Groups: (1) protocol name.
	clojureDefprotocol = regexp.MustCompile(`^\(defprotocol\s+(` + clojureSymbol + `)`)

	// clojureDefrecord matches record type declarations.
	// Groups: (1) record name.
	clojureDefrecord = regexp.MustCompile(`^\(defrecord\s+(` + clojureSymbol + `)`)

	// clojureDeftype matches type declarations.
	// Groups: (1) type name.
	clojureDeftype = regexp.MustCompile(`^\(deftype\s+(` + clojureSymbol + `)`)

	// clojureDefmulti matches multimethod dispatch declarations.
	// Groups: (1) multimethod name.
	clojureDefmulti = regexp.MustCompile(`^\(defmulti\s+(` + clojureSymbol + `)`)

	// clojureDef matches def and defonce variable declarations.
	// Pattern: def(?:once)? ensures defn, defmacro, etc. are not matched
	// (after "def" the regex expects "once" or whitespace, not "n" or "m").
	// Groups: (1) var name.
	clojureDef = regexp.MustCompile(`^\(def(?:once)?\s+(` + clojureSymbol + `)`)

	clojureGenerated = regexp.MustCompile(
		`DO NOT EDIT|auto.?generated|This file was (automatically )?generated|Generated by|@generated`)
)

// parseClojureFile builds a FileMap for a Clojure source file (.clj, .cljs,
// .cljc). In Clojure every top-level declaration is a parenthesized form at
// paren depth 0. Block depth is tracked via paren balance; the scanner skips
// "..." string content and ; line comments.
//
// Collected at depth 0:
//   - Namespace: (ns name ...) — used as the module identifier in the label
//   - Structural: defprotocol, defrecord, deftype
//   - Defs: defn, defn-, defmacro, defmulti, def, defonce
//
// The entire file maps to one entry. Structural names appear first in the
// Kind label, followed by function names, up to 4 with +N overflow.
func parseClojureFile(src, filePath string) (digest.FileMap, bool) {
	lines := splitLines(src)
	if len(lines) == 0 {
		return digest.FileMap{}, false
	}
	if !hasClojureStructure(lines) {
		return digest.FileMap{}, false
	}

	ext := strings.ToLower(filepath.Ext(filePath))
	isCljs := ext == ".cljs"

	generated := false
	for _, l := range lines[:min(len(lines), 10)] {
		if clojureGenerated.MatchString(l) {
			generated = true
			break
		}
	}

	var nsName string
	var structural []string // defprotocol, defrecord, deftype names
	var defs []string       // defn, defmacro, defmulti, def, defonce names
	seenStructural := make(map[string]bool)
	seenDefs := make(map[string]bool)

	depth := 0
	inString := false

	for _, raw := range lines {
		trimmed := strings.TrimSpace(raw)

		// Collect at depth 0 BEFORE updating depth.
		// Skip collection for blank lines and real comment lines (not when
		// we're inside a multiline string — a semicolon-prefixed line can be
		// string content, not a comment).
		if depth == 0 && trimmed != "" && (inString || !strings.HasPrefix(trimmed, ";")) {
			if m := clojureNS.FindStringSubmatch(trimmed); m != nil {
				if nsName == "" {
					nsName = m[1]
				}
			} else if m := clojureDefprotocol.FindStringSubmatch(trimmed); m != nil {
				name := m[1]
				if !seenStructural[name] {
					structural = append(structural, name)
					seenStructural[name] = true
				}
			} else if m := clojureDefrecord.FindStringSubmatch(trimmed); m != nil {
				name := m[1]
				if !seenStructural[name] {
					structural = append(structural, name)
					seenStructural[name] = true
				}
			} else if m := clojureDeftype.FindStringSubmatch(trimmed); m != nil {
				name := m[1]
				if !seenStructural[name] {
					structural = append(structural, name)
					seenStructural[name] = true
				}
			} else if m := clojureDefn.FindStringSubmatch(trimmed); m != nil {
				name := m[1]
				if !seenDefs[name] {
					defs = append(defs, name)
					seenDefs[name] = true
				}
			} else if m := clojureDefmacro.FindStringSubmatch(trimmed); m != nil {
				name := m[1]
				if !seenDefs[name] {
					defs = append(defs, name)
					seenDefs[name] = true
				}
			} else if m := clojureDefmulti.FindStringSubmatch(trimmed); m != nil {
				name := m[1]
				if !seenDefs[name] {
					defs = append(defs, name)
					seenDefs[name] = true
				}
			} else if m := clojureDef.FindStringSubmatch(trimmed); m != nil {
				name := m[1]
				if !isClojureKeyword(name) && !seenDefs[name] {
					defs = append(defs, name)
					seenDefs[name] = true
				}
			}
		}

		depth += clojureNetDepth(raw, &inString)
		if depth < 0 {
			depth = 0
		}
	}

	if nsName == "" && len(structural) == 0 && len(defs) == 0 {
		return digest.FileMap{}, false
	}

	base := filepath.Base(filePath)
	stem := strings.TrimSuffix(base, filepath.Ext(base))

	// Use the namespace name as the module identifier when available;
	// it is more informative than the filename stem.
	moduleName := stem
	if nsName != "" {
		moduleName = nsName
	}

	combined := append(structural, defs...)
	label := clojureLabel(moduleName, combined)
	summary := clojureSummary(moduleName, len(structural), len(defs), isCljs, generated)

	var symbols []string
	for _, s := range structural {
		symbols = append(symbols, "type "+s)
	}
	for _, d := range defs {
		symbols = append(symbols, "fn "+d)
	}

	return digest.FileMap{
		Summary: summary,
		Map: []digest.MapEntry{{
			Lines: lineRange(1, len(lines)),
			Kind:  label,
		}},
		Symbols: symbols,
	}, true
}

// clojureNetDepth counts the net paren depth change for a single line,
// skipping "..." string content and ; line comments. Brackets [] and
// braces {} are not tracked — only () matters for detecting top-level forms.
// inString persists across calls for multiline strings.
func clojureNetDepth(line string, inString *bool) int {
	net := 0
	for i := 0; i < len(line); i++ {
		ch := line[i]
		if *inString {
			if ch == '\\' && i+1 < len(line) {
				i++ // skip escaped char
			} else if ch == '"' {
				*inString = false
			}
			continue
		}
		switch ch {
		case ';':
			return net // rest of line is a comment
		case '"':
			*inString = true
		case '(':
			net++
		case ')':
			net--
		}
	}
	return net
}

func isClojureKeyword(s string) bool {
	switch s {
	case "true", "false", "nil":
		return true
	}
	return false
}

func hasClojureStructure(lines []string) bool {
	for _, l := range lines {
		trimmed := strings.TrimSpace(l)
		if clojureNS.MatchString(trimmed) ||
			clojureDefn.MatchString(trimmed) ||
			clojureDefmacro.MatchString(trimmed) ||
			clojureDefprotocol.MatchString(trimmed) ||
			clojureDefrecord.MatchString(trimmed) ||
			clojureDeftype.MatchString(trimmed) ||
			clojureDefmulti.MatchString(trimmed) ||
			clojureDef.MatchString(trimmed) {
			return true
		}
	}
	return false
}

func clojureLabel(moduleName string, names []string) string {
	label := "module " + moduleName
	if len(names) == 0 {
		return label
	}
	displayed := names
	suffix := ""
	if len(displayed) > 4 {
		displayed = displayed[:4]
		suffix = fmt.Sprintf(" (+%d)", len(names)-4)
	}
	return label + " — " + strings.Join(displayed, ", ") + suffix
}

func clojureSummary(moduleName string, structuralCount, defCount int, isCljs, generated bool) string {
	lang := "Clojure"
	if isCljs {
		lang = "ClojureScript"
	}
	s := lang + " — " + moduleName
	var parts []string
	if structuralCount == 1 {
		parts = append(parts, "1 type")
	} else if structuralCount > 1 {
		parts = append(parts, fmt.Sprintf("%d types", structuralCount))
	}
	if defCount == 1 {
		parts = append(parts, "1 function")
	} else if defCount > 1 {
		parts = append(parts, fmt.Sprintf("%d functions", defCount))
	}
	if len(parts) > 0 {
		s += ", " + strings.Join(parts, ", ")
	}
	if generated {
		s += " — generated, do not edit directly"
	}
	return s
}
