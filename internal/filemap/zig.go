package filemap

import (
	"fmt"
	"path/filepath"
	"regexp"
	"strings"

	"github.com/kaushal/skim/internal/digest"
)

var (
	// zigFunc matches function declarations at column 0.
	// Handles pub, export, extern, inline, and noinline visibility/calling
	// convention modifiers in any combination before the fn keyword.
	// Groups: (1) function name.
	zigFunc = regexp.MustCompile(
		`^(?:pub\s+)?(?:export\s+|extern\s+)?(?:inline\s+|noinline\s+)?fn\s+([A-Za-z_][A-Za-z0-9_]*)`)

	// zigType matches type declarations of the form:
	//   (pub )? const TypeName = (packed|extern)? struct/union/enum/opaque
	// Covers all aggregate type forms including tagged unions (union(enum)),
	// packed/extern structs, and opaque types.
	// Groups: (1) type name.
	zigType = regexp.MustCompile(
		`^(?:pub\s+)?const\s+([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(?:extern\s+|packed\s+)?(?:struct|union|enum|opaque)\b`)

	zigGenerated = regexp.MustCompile(
		`DO NOT EDIT|auto.?generated|This file was (automatically )?generated|Generated by|@generated`)
)

// parseZigFile builds a FileMap for a Zig source file.
//
// Zig uses only // single-line comments and {/} braces for scoping. All
// top-level declarations start at column 0; struct fields, methods, and local
// variables are indented inside their enclosing braces and are skipped by the
// column-0 rule.
//
// Collected at column 0:
//   - (pub)? (export|extern)? (inline|noinline)? fn name(...) — functions
//   - (pub)? const TypeName = (packed|extern)? struct/union/enum/opaque — types
//
// The file stem is used as the label base (Zig has no module declaration;
// the file name is the implicit module name). Types appear before functions
// in the Kind label; up to 4 items shown with +N overflow.
func parseZigFile(src, filePath string) (digest.FileMap, bool) {
	lines := splitLines(src)
	if len(lines) == 0 {
		return digest.FileMap{}, false
	}
	if !hasZigStructure(lines) {
		return digest.FileMap{}, false
	}

	generated := false
	for _, l := range lines[:min(len(lines), 10)] {
		if zigGenerated.MatchString(l) {
			generated = true
			break
		}
	}

	var structural []string // type names from const X = struct/union/enum
	var defs []string       // function names
	seenStructural := make(map[string]bool)
	seenDefs := make(map[string]bool)

	for _, raw := range lines {
		trimmed := strings.TrimSpace(raw)
		if trimmed == "" || strings.HasPrefix(trimmed, "//") {
			continue
		}

		// All top-level declarations in Zig start at column 0. Struct fields,
		// methods, and local variables are indented and skipped here.
		if len(raw) > 0 && (raw[0] == ' ' || raw[0] == '\t') {
			continue
		}

		// Type declaration: (pub)? const TypeName = struct/union/enum/opaque
		if m := zigType.FindStringSubmatch(trimmed); m != nil {
			name := m[1]
			if !seenStructural[name] {
				structural = append(structural, name)
				seenStructural[name] = true
			}
			continue
		}

		// Function declaration: (pub)? (export|extern)? (inline|noinline)? fn name
		if m := zigFunc.FindStringSubmatch(trimmed); m != nil {
			name := m[1]
			if !isZigKeyword(name) && !seenDefs[name] {
				defs = append(defs, name)
				seenDefs[name] = true
			}
			continue
		}
	}

	if len(structural) == 0 && len(defs) == 0 {
		return digest.FileMap{}, false
	}

	base := filepath.Base(filePath)
	stem := strings.TrimSuffix(base, filepath.Ext(base))

	combined := append(structural, defs...)
	label := zigLabel(stem, combined)
	summary := zigSummary(stem, len(structural), len(defs), generated)

	var symbols []string
	for _, s := range structural {
		symbols = append(symbols, "type "+s)
	}
	for _, d := range defs {
		symbols = append(symbols, "fn "+d)
	}

	return digest.FileMap{
		Summary: summary,
		Map: []digest.MapEntry{{
			Lines: lineRange(1, len(lines)),
			Kind:  label,
		}},
		Symbols: symbols,
	}, true
}

func isZigKeyword(s string) bool {
	switch s {
	case "align", "allowzero", "and", "anyframe", "anytype", "asm",
		"async", "await", "break", "callconv", "catch", "comptime",
		"const", "continue", "defer", "else", "enum", "errdefer",
		"error", "export", "extern", "false", "fn", "for", "if",
		"inline", "noalias", "noinline", "nosuspend", "null", "opaque",
		"or", "orelse", "packed", "pub", "resume", "return", "struct",
		"suspend", "switch", "test", "threadlocal", "true", "try",
		"undefined", "union", "unreachable", "usingnamespace", "var",
		"volatile", "while":
		return true
	}
	return false
}

func hasZigStructure(lines []string) bool {
	for _, l := range lines {
		trimmed := strings.TrimSpace(l)
		if zigFunc.MatchString(trimmed) || zigType.MatchString(trimmed) {
			return true
		}
	}
	return false
}

func zigLabel(stem string, names []string) string {
	label := "module " + stem
	if len(names) == 0 {
		return label
	}
	displayed := names
	suffix := ""
	if len(displayed) > 4 {
		displayed = displayed[:4]
		suffix = fmt.Sprintf(" (+%d)", len(names)-4)
	}
	return label + " — " + strings.Join(displayed, ", ") + suffix
}

func zigSummary(stem string, structuralCount, defCount int, generated bool) string {
	s := "Zig — " + stem
	var parts []string
	if structuralCount == 1 {
		parts = append(parts, "1 type")
	} else if structuralCount > 1 {
		parts = append(parts, fmt.Sprintf("%d types", structuralCount))
	}
	if defCount == 1 {
		parts = append(parts, "1 function")
	} else if defCount > 1 {
		parts = append(parts, fmt.Sprintf("%d functions", defCount))
	}
	if len(parts) > 0 {
		s += ", " + strings.Join(parts, ", ")
	}
	if generated {
		s += " — generated, do not edit directly"
	}
	return s
}
