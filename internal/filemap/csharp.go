package filemap

import (
	"fmt"
	"regexp"
	"strings"

	"github.com/kaushal/skim/internal/digest"
)

var (
	// csTopBlock matches a C# type declaration.
	// Optional attributes ([Serializable] etc.) and access/type-shaping
	// modifiers are consumed; the keyword lands in group 1, the name in group 2.
	// Groups: (1) kind phrase, (2) name
	csTopBlock = regexp.MustCompile(
		`^\s*(?:(?:\[[^\]]*\]\s*)*)` + // optional attributes in brackets
			`(?:(?:public|private|protected|internal|file)\s+)*` +
			`((?:(?:abstract|sealed|static|partial|unsafe|readonly)\s+)*` +
			`(?:(?:record\s+(?:class|struct))|(?:class|struct|interface|enum|record)))\s+` +
			`([A-Za-z_][A-Za-z0-9_]*)`)
	// csMethod matches a method declaration: optional modifiers + return type + name + "(".
	// Groups: (1) name
	csMethod = regexp.MustCompile(
		`^\s*(?:(?:\[[^\]]*\]\s*)*)` + // optional inline attributes
			`(?:(?:public|private|protected|internal|static|virtual|override|abstract|async|sealed|extern|unsafe|new|readonly)\s+)*` +
			`(?:<[^>]*>\s+)?` + // optional type parameters before return type
			`[A-Za-z_@][\w.<>[\]?,\s]*\s+` + // return type (broad)
			`([A-Za-z_][A-Za-z0-9_]*)\s*[(<]`) // method name + "(" or "<" (generic)
	// csProperty matches a property declaration (return type + name + "{").
	// We record properties as entries to exclude from method detection.
	csProperty = regexp.MustCompile(`[{]\s*(?:get|set|init)\b`)
	// csNamespaceBlock matches a block-scoped namespace declaration.
	csNamespaceBlock = regexp.MustCompile(`^\s*namespace\s+[\w.]+\s*$|^\s*namespace\s+[\w.]+\s*{`)
	// csNamespaceFile matches a file-scoped namespace (C# 10+): "namespace Foo;"
	csNamespaceFile = regexp.MustCompile(`^\s*namespace\s+[\w.]+\s*;`)
	// csAttribute matches a standalone attribute line.
	csAttribute = regexp.MustCompile(`^\s*\[`)
	// csComment matches C# single-line comments.
	csComment = regexp.MustCompile(`^\s*//`)
	// csGenerated detects generated C# files.
	csGenerated = regexp.MustCompile(`<auto-generated>|DO NOT EDIT|auto.?generated|This file was automatically generated|Generated by|T4 template`)
)

// csBlock tracks one C# type declaration while parsing.
type csBlock struct {
	kind      string
	name      string
	startLine int
	endLine   int
	methods   []string
}

// parseCSharpFile builds a FileMap from a C# source file. Each top-level type
// declaration (including types inside namespace blocks) becomes one map entry;
// the Kind label lists up to 4 method names with +N overflow.
func parseCSharpFile(src, _ string) (digest.FileMap, bool) {
	lines := splitLines(src)
	if len(lines) == 0 {
		return digest.FileMap{}, false
	}
	if !hasCSharpStructure(lines) {
		return digest.FileMap{}, false
	}

	generated := false
	for _, l := range lines[:min(len(lines), 5)] {
		if csGenerated.MatchString(l) {
			generated = true
			break
		}
	}

	var blocks []*csBlock
	var cur *csBlock
	var pendingBlock *csBlock // waiting for opening "{"
	depth := 0
	// outerDepth tracks brace depth of namespace blocks and other non-type
	// scopes at the top level (depth when cur == nil).
	outerDepth := 0
	bcDepth := 0   // C# block comment nesting (/* ... */ are not nested in C#, but track for uniformity)
	inTextBlock := false // verbatim strings @"..." and raw strings """..."""

	closeBlock := func(endLine int) {
		if cur != nil {
			cur.endLine = endLine
			blocks = append(blocks, cur)
			cur = nil
		}
	}

	for i, raw := range lines {
		lineNo := i + 1
		trimmed := strings.TrimSpace(raw)

		if trimmed == "" {
			continue
		}

		// C# raw string tracking ("""...""").
		// When already inside a multi-line raw string, wait for closing """.
		if inTextBlock {
			if strings.Contains(trimmed, `"""`) {
				inTextBlock = false
			}
			continue
		}
		// Only enter raw-string mode when """ opens on this line but does NOT
		// close on the same line. Self-contained single-line """ ... """ pairs
		// are handled inside csNetBraces so braces within them are skipped.
		if csHasUnclosedTripleQuote(trimmed) {
			inTextBlock = true
			continue
		}

		startedInBC := bcDepth > 0

		if pendingBlock != nil {
			d := csNetBraces(raw, &bcDepth)
			if d > 0 {
				cur = pendingBlock
				depth = d
				pendingBlock = nil
			} else if d < 0 {
				pendingBlock = nil
			}
			continue
		}

		if cur != nil {
			// Collect methods at depth 1 BEFORE updating depth.
			if !startedInBC && depth == 1 &&
				!csAttribute.MatchString(raw) &&
				!csProperty.MatchString(raw) {
				if m := csMethod.FindStringSubmatch(trimmed); m != nil {
					name := m[1]
					if !isCSharpKeyword(name) {
						cur.methods = append(cur.methods, name)
					}
				}
			}
			depth += csNetBraces(raw, &bcDepth)
			if depth <= 0 {
				closeBlock(lineNo)
				depth = 0
			}
			continue
		}

		// Top level (or inside a namespace block at outerDepth > 0).
		if startedInBC {
			csNetBraces(raw, &bcDepth)
			continue
		}
		if csComment.MatchString(raw) {
			continue
		}
		if csNamespaceFile.MatchString(raw) {
			continue // file-scoped namespace: no braces, just skip
		}

		// Type declaration (may appear at depth 0 or inside a namespace block).
		if m := csTopBlock.FindStringSubmatch(trimmed); m != nil {
			kind := strings.TrimSpace(m[1])
			b := &csBlock{kind: kind, name: m[2], startLine: lineNo}
			d := csNetBraces(raw, &bcDepth)
			if d > 0 {
				cur = b
				depth = d
			} else {
				pendingBlock = b
			}
			continue
		}

		// Namespace block — track outer depth so closing "}" is absorbed.
		if csNamespaceBlock.MatchString(raw) {
			d := csNetBraces(raw, &bcDepth)
			outerDepth += d
			continue
		}

		// Standalone attribute line ([Serializable], [HttpGet], etc.) — skip.
		if csAttribute.MatchString(raw) {
			continue
		}

		// Bare closing brace at the outer level — namespace or outer scope closing.
		d := csNetBraces(raw, &bcDepth)
		if d < 0 && outerDepth > 0 {
			outerDepth += d
			if outerDepth < 0 {
				outerDepth = 0
			}
		}
	}
	// Flush any pending block that never got an opening "{" (e.g. a record
	// struct with only a primary constructor and no body).
	if pendingBlock != nil {
		pendingBlock.endLine = len(lines)
		blocks = append(blocks, pendingBlock)
		pendingBlock = nil
	}
	closeBlock(len(lines))

	if len(blocks) == 0 {
		return digest.FileMap{}, false
	}

	var entries []digest.MapEntry
	var symbols []string
	for _, b := range blocks {
		label := csBlockLabel(b)
		if len(symbols) < 40 {
			symbols = append(symbols, b.kind+" "+b.name)
		}
		entries = append(entries, digest.MapEntry{
			Lines: lineRange(b.startLine, b.endLine),
			Kind:  label,
		})
	}

	return digest.FileMap{
		Summary: csSummary(blocks, generated),
		Map:     entries,
		Symbols: symbols,
	}, true
}

// csNetBraces counts net brace depth for a C# line, ignoring braces inside
// double-quoted strings, character literals, // comments, and /* */ block
// comments. bcDepth carries block-comment depth across lines.
// Note: C# does not support nested block comments, but we use int for
// uniformity with the Swift parser.
func csNetBraces(line string, bcDepth *int) int {
	depth := 0
	inStr := false
	for i := 0; i < len(line); i++ {
		ch := line[i]
		if *bcDepth > 0 {
			if ch == '*' && i+1 < len(line) && line[i+1] == '/' {
				*bcDepth--
				i++
			}
			continue
		}
		if inStr {
			if ch == '\\' {
				i++
				continue
			}
			if ch == '"' {
				inStr = false
			}
			continue
		}
		switch ch {
		case '"':
			// Check for raw string literal """...""".
			if i+2 < len(line) && line[i+1] == '"' && line[i+2] == '"' {
				i += 3
				// Scan for the closing """ on this same line.
				found := false
				for i+2 < len(line) {
					if line[i] == '"' && line[i+1] == '"' && line[i+2] == '"' {
						i += 2 // loop will advance one more
						found = true
						break
					}
					i++
				}
				if !found {
					// Multi-line raw string: rest of line is content; stop counting.
					return depth
				}
				break
			}
			inStr = true
		case '\'':
			i++
			for i < len(line) {
				if line[i] == '\\' {
					i++
				} else if line[i] == '\'' {
					break
				}
				i++
			}
		case '@':
			// Verbatim string @"...": braces inside are literal; skip until
			// closing unescaped quote. Doubled quotes ("") are the escape form.
			if i+1 < len(line) && line[i+1] == '"' {
				i += 2
				for i < len(line) {
					if line[i] == '"' {
						if i+1 < len(line) && line[i+1] == '"' {
							i++ // skip doubled quote
						} else {
							break
						}
					}
					i++
				}
			}
		case '/':
			if i+1 < len(line) && line[i+1] == '/' {
				return depth
			}
			if i+1 < len(line) && line[i+1] == '*' {
				*bcDepth = 1
				i++
			}
		case '{':
			depth++
		case '}':
			depth--
		}
	}
	return depth
}

// csHasUnclosedTripleQuote reports whether s contains a """ that opens a raw
// string literal that does not close on the same line. Self-contained pairs
// like `"""foo"""` return false; a lone `"""` opener returns true.
func csHasUnclosedTripleQuote(s string) bool {
	for {
		idx := strings.Index(s, `"""`)
		if idx < 0 {
			return false
		}
		rest := s[idx+3:]
		closeIdx := strings.Index(rest, `"""`)
		if closeIdx < 0 {
			return true // opens but does not close
		}
		s = rest[closeIdx+3:] // both open and close on this line; keep scanning
	}
}

// isCSharpKeyword reports whether s is a C# keyword that could match as a
// method name in the broad method regex.
func isCSharpKeyword(s string) bool {
	switch s {
	case "if", "for", "foreach", "while", "switch", "return", "new", "throw",
		"catch", "try", "else", "do", "case", "break", "continue", "using",
		"class", "interface", "struct", "enum", "record", "namespace", "delegate",
		"event", "operator", "implicit", "explicit", "typeof", "sizeof", "checked",
		"unchecked", "lock", "fixed", "unsafe", "var", "void", "get", "set", "init",
		"add", "remove", "yield", "await", "async", "where", "select", "from",
		"in", "is", "as", "base", "this", "default", "null", "true", "false":
		return true
	}
	return false
}

// csBlockLabel builds the Kind label for a C# block entry.
func csBlockLabel(b *csBlock) string {
	label := b.kind + " " + b.name
	if len(b.methods) == 0 {
		return label
	}
	displayed := b.methods
	suffix := ""
	if len(displayed) > 4 {
		displayed = displayed[:4]
		suffix = fmt.Sprintf(" (+%d)", len(b.methods)-4)
	}
	return label + " — " + strings.Join(displayed, ", ") + suffix
}

// csSummary builds the top-level summary line.
func csSummary(blocks []*csBlock, generated bool) string {
	counts := map[string]int{}
	methodCount := 0
	for _, b := range blocks {
		counts[b.kind]++
		methodCount += len(b.methods)
	}

	ordered := []string{
		"class", "abstract class", "sealed class", "static class",
		"partial class", "record", "record class", "record struct",
		"struct", "interface", "enum",
	}
	var parts []string
	for _, k := range ordered {
		n := counts[k]
		if n == 0 {
			continue
		}
		if n == 1 {
			parts = append(parts, "1 "+k)
		} else {
			words := strings.Fields(k)
			words[len(words)-1] += "s"
			parts = append(parts, fmt.Sprintf("%d %s", n, strings.Join(words, " ")))
		}
	}
	if methodCount == 1 {
		parts = append(parts, "1 method")
	} else if methodCount > 1 {
		parts = append(parts, fmt.Sprintf("%d methods", methodCount))
	}

	summary := "C# — " + strings.Join(parts, ", ")
	if generated {
		summary += " — generated, do not edit directly"
	}
	return summary
}

// hasCSharpStructure returns true when at least one class/struct/interface/
// enum/record declaration is present.
func hasCSharpStructure(lines []string) bool {
	for _, l := range lines {
		if csTopBlock.MatchString(l) {
			return true
		}
	}
	return false
}
