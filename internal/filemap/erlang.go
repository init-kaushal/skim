package filemap

import (
	"fmt"
	"path/filepath"
	"regexp"
	"strings"

	"github.com/kaushal/skim/internal/digest"
)

var (
	// erlangModule matches -module(name). declarations.
	// Groups: (1) module name (atom).
	erlangModule = regexp.MustCompile(`^-module\(([a-z][a-z0-9_@]*)\)`)

	// erlangRecord matches -record(name, {fields}) declarations.
	// Groups: (1) record name.
	erlangRecord = regexp.MustCompile(`^-record\(([a-z][a-z0-9_]*)`)

	// erlangType matches -type name(...) :: ... and -opaque name(...) :: ...
	// Groups: (1) type name.
	erlangType = regexp.MustCompile(`^-(?:type|opaque)\s+([a-z][a-z0-9_]*)`)

	// erlangDefine matches -define(NAME, value) macros.
	// Groups: (1) macro name.
	erlangDefine = regexp.MustCompile(`^-define\(([A-Za-z][A-Za-z0-9_]*)`)

	// erlangFunc matches a function clause: name(Args) -> ...
	// In Erlang, only function clauses start at column 0 with a lowercase
	// atom followed by '('. Module attributes start with '-'.
	// Groups: (1) function name.
	erlangFunc = regexp.MustCompile(`^([a-z][a-z0-9_@]*)\s*\(`)

	erlangGenerated = regexp.MustCompile(
		`DO NOT EDIT|auto.?generated|This file was (automatically )?generated|Generated by|@generated`)
)

// parseErlangFile builds a FileMap for an Erlang source (.erl) or header
// (.hrl) file.
//
// Erlang has only single-line comments (% ...) and no block comments, which
// simplifies scanning. All top-level forms start at column 0:
//   - Module attributes:  -attr(...).\n
//   - Function clauses:   name(Args) -> body.\n
//
// .erl: collects -module name, -record and -type as structural, function
// clauses as defs.
// .hrl: collects -record and -type as structural, -define macros as defs.
//
// The module name (when found) replaces the file stem as the label base.
// Structural items appear before function/macro names in the Kind label;
// up to 4 are shown with +N overflow.
func parseErlangFile(src, filePath string) (digest.FileMap, bool) {
	lines := splitLines(src)
	if len(lines) == 0 {
		return digest.FileMap{}, false
	}
	if !hasErlangStructure(lines) {
		return digest.FileMap{}, false
	}

	ext := strings.ToLower(filepath.Ext(filePath))
	isHeader := ext == ".hrl"

	generated := false
	for _, l := range lines[:min(len(lines), 10)] {
		if erlangGenerated.MatchString(l) {
			generated = true
			break
		}
	}

	var moduleName string
	var structural []string // records and types
	var defs []string       // functions (.erl) or macros (.hrl)
	seenStructural := make(map[string]bool)
	seenDefs := make(map[string]bool)
	// structuralKind tracks whether a structural entry is a record or type,
	// so we can emit the correct symbol prefix.
	structuralKind := make(map[string]string)

	for _, raw := range lines {
		trimmed := strings.TrimSpace(raw)
		if trimmed == "" || strings.HasPrefix(trimmed, "%") {
			continue
		}

		// All Erlang top-level forms start at column 0.
		if len(raw) > 0 && (raw[0] == ' ' || raw[0] == '\t') {
			continue
		}

		if strings.HasPrefix(trimmed, "-") {
			// Module attribute.
			if m := erlangModule.FindStringSubmatch(trimmed); m != nil {
				if moduleName == "" {
					moduleName = m[1]
				}
				continue
			}
			if m := erlangRecord.FindStringSubmatch(trimmed); m != nil {
				name := m[1]
				if !seenStructural[name] {
					structural = append(structural, name)
					seenStructural[name] = true
					structuralKind[name] = "record"
				}
				continue
			}
			if m := erlangType.FindStringSubmatch(trimmed); m != nil {
				name := m[1]
				if !seenStructural[name] {
					structural = append(structural, name)
					seenStructural[name] = true
					structuralKind[name] = "type"
				}
				continue
			}
			if isHeader {
				// Collect macro names from .hrl files.
				if m := erlangDefine.FindStringSubmatch(trimmed); m != nil {
					name := m[1]
					if !seenDefs[name] {
						defs = append(defs, name)
						seenDefs[name] = true
					}
				}
			}
			// All other attributes (-export, -import, -behaviour, -spec, …) skipped.
			continue
		}

		if !isHeader {
			// Function clause: name(Args) -> ...
			// Multiple clauses of the same function dedup via seenDefs.
			if m := erlangFunc.FindStringSubmatch(trimmed); m != nil {
				name := m[1]
				if !seenDefs[name] {
					defs = append(defs, name)
					seenDefs[name] = true
				}
			}
		}
	}

	if moduleName == "" && len(structural) == 0 && len(defs) == 0 {
		return digest.FileMap{}, false
	}

	base := filepath.Base(filePath)
	stem := strings.TrimSuffix(base, filepath.Ext(base))

	labelBase := stem
	if moduleName != "" {
		labelBase = moduleName
	}

	combined := append(structural, defs...)
	label := erlangLabel(labelBase, combined)
	summary := erlangSummary(labelBase, len(structural), len(defs), isHeader, generated)

	var symbols []string
	for _, s := range structural {
		kind := structuralKind[s]
		if kind == "" {
			kind = "type"
		}
		symbols = append(symbols, kind+" "+s)
	}
	for _, d := range defs {
		if isHeader {
			symbols = append(symbols, "macro "+d)
		} else {
			symbols = append(symbols, "fn "+d)
		}
	}

	return digest.FileMap{
		Summary: summary,
		Map: []digest.MapEntry{{
			Lines: lineRange(1, len(lines)),
			Kind:  label,
		}},
		Symbols: symbols,
	}, true
}

func hasErlangStructure(lines []string) bool {
	for _, l := range lines {
		trimmed := strings.TrimSpace(l)
		if erlangModule.MatchString(trimmed) ||
			erlangRecord.MatchString(trimmed) ||
			erlangType.MatchString(trimmed) ||
			erlangDefine.MatchString(trimmed) ||
			erlangFunc.MatchString(trimmed) {
			return true
		}
	}
	return false
}

func erlangLabel(labelBase string, names []string) string {
	label := "module " + labelBase
	if len(names) == 0 {
		return label
	}
	displayed := names
	suffix := ""
	if len(displayed) > 4 {
		displayed = displayed[:4]
		suffix = fmt.Sprintf(" (+%d)", len(names)-4)
	}
	return label + " — " + strings.Join(displayed, ", ") + suffix
}

func erlangSummary(labelBase string, structuralCount, defCount int, isHeader, generated bool) string {
	lang := "Erlang"
	if isHeader {
		lang = "Erlang header"
	}
	s := lang + " — " + labelBase
	var parts []string
	if structuralCount == 1 {
		parts = append(parts, "1 type")
	} else if structuralCount > 1 {
		parts = append(parts, fmt.Sprintf("%d types", structuralCount))
	}
	defLabel := "function"
	if isHeader {
		defLabel = "macro"
	}
	if defCount == 1 {
		parts = append(parts, "1 "+defLabel)
	} else if defCount > 1 {
		parts = append(parts, fmt.Sprintf("%d %ss", defCount, defLabel))
	}
	if len(parts) > 0 {
		s += ", " + strings.Join(parts, ", ")
	}
	if generated {
		s += " — generated, do not edit directly"
	}
	return s
}
