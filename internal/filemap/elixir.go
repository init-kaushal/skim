package filemap

import (
	"fmt"
	"regexp"
	"strings"

	"github.com/kaushal/skim/internal/digest"
)

var (
	// elixirTopBlock matches a top-level module/protocol/implementation block.
	// Elixir module names are dot-separated PascalCase (e.g. MyApp.Router).
	// Groups: (1) keyword (defmodule|defprotocol|defimpl), (2) primary name.
	elixirTopBlock = regexp.MustCompile(
		`^\s*(def(?:module|protocol|impl))\s+([A-Z][A-Za-z0-9_.]*)`)

	// elixirDef matches a public or private function/macro declaration at depth 1.
	// Elixir function names may include ? (predicate) and ! (bang) suffixes.
	// Groups: (1) function name.
	elixirDef = regexp.MustCompile(
		`^\s*defp?\s+([a-z_][A-Za-z0-9_?!]*)`)

	elixirComment   = regexp.MustCompile(`^\s*#`)
	elixirImport    = regexp.MustCompile(`^\s*(?:import|alias|require|use)\s`)
	elixirGenerated = regexp.MustCompile(`DO NOT EDIT|auto.?generated|This file was (automatically )?generated|Generated by|@generated`)
)

type elixirBlock struct {
	kind      string
	name      string
	startLine int
	endLine   int
	fns       []string
	seen      map[string]bool // dedup: multi-clause functions appear once
}

// parseElixirFile builds a FileMap from an Elixir source file. Each top-level
// defmodule/defprotocol/defimpl block becomes one map entry; the Kind label
// lists up to 4 unique function names with +N overflow.
func parseElixirFile(src, _ string) (digest.FileMap, bool) {
	lines := splitLines(src)
	if len(lines) == 0 {
		return digest.FileMap{}, false
	}
	if !hasElixirStructure(lines) {
		return digest.FileMap{}, false
	}

	generated := false
	for _, l := range lines[:min(len(lines), 10)] {
		if elixirGenerated.MatchString(l) {
			generated = true
			break
		}
	}

	var blocks []*elixirBlock
	var cur *elixirBlock
	var pendingBlock *elixirBlock // defmodule with no "do" on same line
	depth := 0
	inTriple := false // true while inside a triple-quoted """ string

	closeBlock := func(endLine int) {
		if cur != nil {
			cur.endLine = endLine
			blocks = append(blocks, cur)
			cur = nil
		}
	}

	for i, raw := range lines {
		lineNo := i + 1
		trimmed := strings.TrimSpace(raw)

		if trimmed == "" {
			continue
		}

		// Lines inside triple-quoted strings are structurally invisible.
		if inTriple {
			if strings.Contains(trimmed, `"""`) {
				inTriple = false
			}
			continue
		}
		// Opening """ on this line toggles triple-quote mode for following lines.
		// Count occurrences: odd → mode changed; even → opened and closed on same line.
		if cnt := strings.Count(trimmed, `"""`); cnt%2 == 1 {
			inTriple = true
			// The line itself may still have code before the """; skip comment and
			// keyword counting for simplicity (rare in Elixir practice).
			continue
		}

		// Skip pure comment lines and import/alias lines at top level.
		if elixirComment.MatchString(raw) {
			continue
		}

		if pendingBlock != nil {
			d := elixirNetBlocks(raw, &inTriple)
			if d > 0 {
				cur = pendingBlock
				depth = d
				pendingBlock = nil
			} else if d < 0 {
				pendingBlock = nil
			}
			continue
		}

		if cur != nil {
			// Collect function names at depth 1 BEFORE updating depth.
			if depth == 1 {
				if m := elixirDef.FindStringSubmatch(trimmed); m != nil {
					name := m[1]
					if !isElixirKeyword(name) && !cur.seen[name] {
						cur.fns = append(cur.fns, name)
						cur.seen[name] = true
					}
				}
			}
			depth += elixirNetBlocks(raw, &inTriple)
			if depth <= 0 {
				closeBlock(lineNo)
				depth = 0
			}
			continue
		}

		// Top level.
		if elixirImport.MatchString(raw) {
			continue
		}

		if m := elixirTopBlock.FindStringSubmatch(trimmed); m != nil {
			b := &elixirBlock{
				kind:      m[1],
				name:      m[2],
				startLine: lineNo,
				seen:      make(map[string]bool),
			}
			d := elixirNetBlocks(raw, &inTriple)
			if d > 0 {
				cur = b
				depth = d
			} else {
				// No "do" on this line (multi-line header); wait for "do".
				pendingBlock = b
			}
			continue
		}

		elixirNetBlocks(raw, &inTriple) // advance inTriple state
	}
	closeBlock(len(lines))

	if len(blocks) == 0 {
		return digest.FileMap{}, false
	}

	var entries []digest.MapEntry
	var symbols []string
	for _, b := range blocks {
		label := elixirBlockLabel(b)
		if len(symbols) < 40 {
			symbols = append(symbols, b.kind+" "+b.name)
		}
		entries = append(entries, digest.MapEntry{
			Lines: lineRange(b.startLine, b.endLine),
			Kind:  label,
		})
	}

	return digest.FileMap{
		Summary: elixirSummary(blocks, generated),
		Map:     entries,
		Symbols: symbols,
	}, true
}

// elixirNetBlocks counts the net block depth change for a single Elixir line.
//
// Opens (+1): word-boundary "do" not followed by ":" (keyword pair), and "fn".
// Closes (-1): word-boundary "end".
//
// Content inside double-quoted strings ("…"), triple-quoted strings ("""…"""),
// and # comments is skipped. Single-quoted charlists use the same escaping as
// double-quoted strings and are treated equivalently.
func elixirNetBlocks(line string, inTriple *bool) int {
	net := 0
	inStr := false
	inSingle := false // single-quoted charlist e.g. 'end' — must not count as block closer
	for i := 0; i < len(line); i++ {
		ch := line[i]

		// Triple-quoted string handling.
		if *inTriple {
			if ch == '"' && i+2 < len(line) && line[i+1] == '"' && line[i+2] == '"' {
				*inTriple = false
				i += 2
			}
			continue
		}

		// Single-line double-quoted string handling.
		if inStr {
			if ch == '\\' {
				i++
				continue
			}
			if ch == '"' {
				inStr = false
			}
			continue
		}

		// Single-quoted charlist handling (e.g. 'end', 'do').
		if inSingle {
			if ch == '\\' {
				i++
				continue
			}
			if ch == '\'' {
				inSingle = false
			}
			continue
		}

		// Detect """ before single '"'.
		if ch == '"' {
			if i+2 < len(line) && line[i+1] == '"' && line[i+2] == '"' {
				*inTriple = true
				i += 2
				continue
			}
			inStr = true
			continue
		}

		// Single-quoted charlist start.
		if ch == '\'' {
			inSingle = true
			continue
		}

		// Single-line comment.
		if ch == '#' {
			return net
		}

		// Word-boundary token checks.
		prevIsId := i > 0 && isElixirIdChar(line[i-1])
		if prevIsId {
			continue
		}

		// "do" — block opener, unless followed by ":"
		if ch == 'd' && i+1 < len(line) && line[i+1] == 'o' {
			after := i + 2
			if after < len(line) && isElixirIdChar(line[after]) {
				continue // part of a longer identifier (do_something, done, etc.)
			}
			if after < len(line) && line[after] == ':' {
				// "do:" keyword pair — not a block opener
				i = after
				continue
			}
			net++
			i = after - 1
			continue
		}

		// "fn" — anonymous function opener
		if ch == 'f' && i+1 < len(line) && line[i+1] == 'n' {
			after := i + 2
			if after < len(line) && isElixirIdChar(line[after]) {
				continue
			}
			net++
			i = after - 1
			continue
		}

		// "end" — block closer
		if ch == 'e' && i+2 < len(line) && line[i+1] == 'n' && line[i+2] == 'd' {
			after := i + 3
			if after < len(line) && isElixirIdChar(line[after]) {
				continue
			}
			net--
			i = after - 1
			continue
		}
	}
	return net
}

// isElixirIdChar returns true for characters that can appear inside an Elixir
// identifier, including the ? and ! suffixes on predicate/bang functions.
func isElixirIdChar(ch byte) bool {
	return ch == '_' || ch == '?' || ch == '!' ||
		(ch >= 'a' && ch <= 'z') || (ch >= 'A' && ch <= 'Z') || (ch >= '0' && ch <= '9')
}

// isElixirKeyword filters control-flow and reserved words that could be
// falsely captured by elixirDef (e.g. "if", "for", "with" at depth 1 start
// with lowercase, but won't match def/defp anyway — kept for safety).
func isElixirKeyword(s string) bool {
	switch s {
	case "if", "else", "unless", "case", "cond", "with", "for", "receive",
		"try", "catch", "rescue", "after", "raise", "throw", "do", "end",
		"when", "and", "or", "not", "in", "fn", "true", "false", "nil":
		return true
	}
	return false
}

func elixirBlockLabel(b *elixirBlock) string {
	label := b.kind + " " + b.name
	if len(b.fns) == 0 {
		return label
	}
	displayed := b.fns
	suffix := ""
	if len(displayed) > 4 {
		displayed = displayed[:4]
		suffix = fmt.Sprintf(" (+%d)", len(b.fns)-4)
	}
	return label + " — " + strings.Join(displayed, ", ") + suffix
}

func elixirSummary(blocks []*elixirBlock, generated bool) string {
	counts := map[string]int{}
	fnCount := 0
	for _, b := range blocks {
		counts[b.kind]++
		fnCount += len(b.fns)
	}

	var parts []string
	for _, k := range []string{"defmodule", "defprotocol", "defimpl"} {
		n := counts[k]
		if n == 0 {
			continue
		}
		label := k[3:] // strip "def" → "module", "protocol", "impl"
		if n == 1 {
			parts = append(parts, "1 "+label)
		} else {
			parts = append(parts, fmt.Sprintf("%d %ss", n, label))
		}
	}
	if fnCount == 1 {
		parts = append(parts, "1 def")
	} else if fnCount > 1 {
		parts = append(parts, fmt.Sprintf("%d defs", fnCount))
	}

	summary := "Elixir — " + strings.Join(parts, ", ")
	if generated {
		summary += " — generated, do not edit directly"
	}
	return summary
}

func hasElixirStructure(lines []string) bool {
	for _, l := range lines {
		if elixirTopBlock.MatchString(l) {
			return true
		}
	}
	return false
}
