package filemap

import (
	"fmt"
	"path/filepath"
	"regexp"
	"strings"

	"github.com/kaushal/skim/internal/digest"
)

var (
	// juliaFunc matches top-level function declarations (long form).
	// Captures qualified names like Base.iterate as well as plain ones.
	// Groups: (1) function name (possibly qualified with dots).
	juliaFunc = regexp.MustCompile(
		`^function\s+((?:[A-Za-z_][A-Za-z0-9_!?]*\.)*[A-Za-z_][A-Za-z0-9_!?]*)`)

	// juliaStruct matches struct and mutable struct declarations.
	// Groups: (1) type name.
	juliaStruct = regexp.MustCompile(`^(?:mutable\s+)?struct\s+([A-Za-z_][A-Za-z0-9_]*)`)

	// juliaAbstract matches abstract type declarations.
	// Groups: (1) type name.
	juliaAbstract = regexp.MustCompile(`^abstract\s+type\s+([A-Za-z_][A-Za-z0-9_]*)`)

	// juliaModule matches module and baremodule declarations.
	// Groups: (1) module name.
	juliaModule = regexp.MustCompile(`^(?:bare)?module\s+([A-Za-z_][A-Za-z0-9_]*)`)

	// juliaMacro matches macro declarations.
	// Groups: (1) macro name.
	juliaMacro = regexp.MustCompile(`^macro\s+([A-Za-z_][A-Za-z0-9_!]*)`)

	// juliaConst matches top-level constant declarations.
	// Groups: (1) constant name.
	juliaConst = regexp.MustCompile(`^const\s+([A-Za-z_][A-Za-z0-9_]*)`)

	// juliaPrimitive matches primitive type declarations.
	// Groups: (1) type name.
	juliaPrimitive = regexp.MustCompile(`^primitive\s+type\s+([A-Za-z_][A-Za-z0-9_]*)`)

	juliaGenerated = regexp.MustCompile(
		`DO NOT EDIT|auto.?generated|This file was (automatically )?generated|Generated by|@generated`)
)

// juliaOpeners is the ordered list of keywords that each open one block
// requiring a matching `end`. Multi-word forms appear before their
// single-word prefixes so the longest match wins.
var juliaOpeners = []string{
	"mutable struct", // before "struct"
	"abstract type",  // before "type" and explicit
	"primitive type", // before "type"
	"baremodule",     // before "module"
	"function",
	"module",
	"struct",
	"macro",
	"if",
	"for",
	"while",
	"let",
	"begin",
	"do",
	"try",
	"quote",
}

// juliaScanState holds multiline scanner state across juliaLineDepth calls.
type juliaScanState struct {
	blockCommentDepth int  // depth of #= ... =# nesting
	inTripleString    bool // inside """..."""
	inBacktick        bool // inside `cmd` command literal
}

// parseJuliaFile builds a FileMap for a Julia source file. Block depth is
// tracked via keyword openers (function, struct, module, if, for, …) and
// `end` tokens, with string and comment content excluded. `end` inside
// brackets (`arr[1:end]`) does not decrement block depth.
//
// The entire file maps to one entry; the Kind label lists modules and types
// first, then functions/macros/consts, up to 4 with +N overflow.
func parseJuliaFile(src, filePath string) (digest.FileMap, bool) {
	lines := splitLines(src)
	if len(lines) == 0 {
		return digest.FileMap{}, false
	}
	if !hasJuliaStructure(lines) {
		return digest.FileMap{}, false
	}

	generated := false
	for _, l := range lines[:min(len(lines), 10)] {
		if juliaGenerated.MatchString(l) {
			generated = true
			break
		}
	}

	var structural []string // module, abstract type, struct names
	var defs []string       // function, macro, const names
	seenStructural := make(map[string]bool)
	seenDefs := make(map[string]bool)

	depth := 0
	st := &juliaScanState{}

	for _, raw := range lines {
		trimmed := strings.TrimSpace(raw)
		if trimmed == "" {
			continue
		}

		// Depth-before-update: collect names at depth 0 BEFORE updating depth.
		if depth == 0 && st.blockCommentDepth == 0 && !st.inTripleString {
			if m := juliaModule.FindStringSubmatch(trimmed); m != nil {
				name := m[1]
				if !seenStructural[name] {
					structural = append(structural, name)
					seenStructural[name] = true
				}
			} else if m := juliaAbstract.FindStringSubmatch(trimmed); m != nil {
				name := m[1]
				if !seenStructural[name] {
					structural = append(structural, name)
					seenStructural[name] = true
				}
			} else if m := juliaStruct.FindStringSubmatch(trimmed); m != nil {
				name := m[1]
				if !seenStructural[name] {
					structural = append(structural, name)
					seenStructural[name] = true
				}
			} else if m := juliaPrimitive.FindStringSubmatch(trimmed); m != nil {
				name := m[1]
				if !seenStructural[name] {
					structural = append(structural, name)
					seenStructural[name] = true
				}
			} else if m := juliaFunc.FindStringSubmatch(trimmed); m != nil {
				name := m[1]
				if !isJuliaKeyword(name) && !seenDefs[name] {
					defs = append(defs, name)
					seenDefs[name] = true
				}
			} else if m := juliaMacro.FindStringSubmatch(trimmed); m != nil {
				name := m[1]
				if !seenDefs[name] {
					defs = append(defs, name)
					seenDefs[name] = true
				}
			} else if m := juliaConst.FindStringSubmatch(trimmed); m != nil {
				name := m[1]
				if !isJuliaKeyword(name) && !seenDefs[name] {
					defs = append(defs, name)
					seenDefs[name] = true
				}
			}
		}

		depth += juliaLineDepth(raw, st)
		if depth < 0 {
			depth = 0
		}
	}

	if len(structural) == 0 && len(defs) == 0 {
		return digest.FileMap{}, false
	}

	base := filepath.Base(filePath)
	stem := strings.TrimSuffix(base, filepath.Ext(base))

	combined := append(structural, defs...)
	label := juliaLabel(stem, combined)
	summary := juliaSummary(stem, len(structural), len(defs), generated)

	var symbols []string
	for _, s := range structural {
		symbols = append(symbols, "type "+s)
	}
	for _, d := range defs {
		symbols = append(symbols, "fn "+d)
	}

	return digest.FileMap{
		Summary: summary,
		Map: []digest.MapEntry{{
			Lines: lineRange(1, len(lines)),
			Kind:  label,
		}},
		Symbols: symbols,
	}, true
}

// juliaLineDepth returns the net block depth change for line.
// Increments for each block-opening keyword (function, struct, if, for, …);
// decrements for each `end` token outside brackets, strings, and comments.
// Updates st in place for multiline state (triple-quoted strings, block comments).
func juliaLineDepth(line string, st *juliaScanState) int {
	net := 0
	bracketDepth := 0
	i := 0
	n := len(line)

	for i < n {
		// Inside #= ... =# block comment (nestable).
		if st.blockCommentDepth > 0 {
			if i+1 < n && line[i] == '#' && line[i+1] == '=' {
				st.blockCommentDepth++
				i += 2
			} else if i+1 < n && line[i] == '=' && line[i+1] == '#' {
				st.blockCommentDepth--
				i += 2
			} else {
				i++
			}
			continue
		}

		// Inside triple-quoted string """...""".
		if st.inTripleString {
			if i+2 < n && line[i] == '"' && line[i+1] == '"' && line[i+2] == '"' {
				st.inTripleString = false
				i += 3
			} else {
				i++
			}
			continue
		}

		// Inside backtick command literal `cmd args`.
		if st.inBacktick {
			if line[i] == '\\' && i+1 < n {
				i += 2
			} else if line[i] == '`' {
				st.inBacktick = false
				i++
			} else {
				i++
			}
			continue
		}

		ch := line[i]

		// Start of backtick command literal.
		if ch == '`' {
			st.inBacktick = true
			i++
			continue
		}

		// Start of triple-quoted string (check before single-quote below).
		if ch == '"' && i+2 < n && line[i+1] == '"' && line[i+2] == '"' {
			st.inTripleString = true
			i += 3
			continue
		}

		// Regular double-quoted string "..." with escape handling.
		if ch == '"' {
			i++
			for i < n {
				if line[i] == '\\' && i+1 < n {
					i += 2
				} else if line[i] == '"' {
					i++
					break
				} else {
					i++
				}
			}
			continue
		}

		// Character literal 'x' or '\n' — skip to avoid '#' misread.
		if ch == '\'' {
			i++
			if i < n && line[i] == '\\' && i+1 < n {
				i += 2
			} else if i < n {
				i++
			}
			if i < n && line[i] == '\'' {
				i++
			}
			continue
		}

		// Block comment start #=
		if ch == '#' && i+1 < n && line[i+1] == '=' {
			st.blockCommentDepth++
			i += 2
			continue
		}

		// Line comment # — rest of line ignored.
		if ch == '#' {
			break
		}

		// Track bracket depth to identify `end` used as subscript (arr[1:end]).
		if ch == '[' {
			bracketDepth++
			i++
			continue
		}
		if ch == ']' {
			if bracketDepth > 0 {
				bracketDepth--
			}
			i++
			continue
		}

		// Keyword matching at word boundary, outside brackets.
		atWordStart := i == 0 || !isJuliaWordChar(line[i-1])
		if atWordStart && bracketDepth == 0 {
			matched := false
			for _, kw := range juliaOpeners {
				if strings.HasPrefix(line[i:], kw) {
					after := i + len(kw)
					if after >= n || !isJuliaWordChar(line[after]) {
						net++
						i = after
						matched = true
						break
					}
				}
			}
			if matched {
				continue
			}
			// `end` as block terminator.
			if strings.HasPrefix(line[i:], "end") {
				after := i + 3
				if after >= n || !isJuliaWordChar(line[after]) {
					net--
					i = after
					continue
				}
			}
		}

		i++
	}
	return net
}

func isJuliaWordChar(c byte) bool {
	return (c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z') ||
		(c >= '0' && c <= '9') || c == '_' || c == '!' || c == '?'
}

func isJuliaKeyword(s string) bool {
	switch s {
	case "abstract", "baremodule", "begin", "break", "catch", "const",
		"continue", "do", "else", "elseif", "end", "export", "false",
		"finally", "for", "function", "global", "if", "import",
		"importall", "in", "let", "local", "macro", "module", "mutable",
		"new", "nothing", "primitive", "quote", "return", "struct",
		"true", "try", "type", "using", "where", "while":
		return true
	}
	return false
}

func hasJuliaStructure(lines []string) bool {
	for _, l := range lines {
		trimmed := strings.TrimSpace(l)
		if juliaFunc.MatchString(trimmed) ||
			juliaStruct.MatchString(trimmed) ||
			juliaAbstract.MatchString(trimmed) ||
			juliaModule.MatchString(trimmed) ||
			juliaMacro.MatchString(trimmed) ||
			juliaConst.MatchString(trimmed) ||
			juliaPrimitive.MatchString(trimmed) {
			return true
		}
	}
	return false
}

func juliaLabel(stem string, names []string) string {
	label := "module " + stem
	if len(names) == 0 {
		return label
	}
	displayed := names
	suffix := ""
	if len(displayed) > 4 {
		displayed = displayed[:4]
		suffix = fmt.Sprintf(" (+%d)", len(names)-4)
	}
	return label + " — " + strings.Join(displayed, ", ") + suffix
}

func juliaSummary(stem string, structuralCount, defCount int, generated bool) string {
	s := "Julia — " + stem
	var parts []string
	if structuralCount == 1 {
		parts = append(parts, "1 type")
	} else if structuralCount > 1 {
		parts = append(parts, fmt.Sprintf("%d types", structuralCount))
	}
	if defCount == 1 {
		parts = append(parts, "1 function")
	} else if defCount > 1 {
		parts = append(parts, fmt.Sprintf("%d functions", defCount))
	}
	if len(parts) > 0 {
		s += ", " + strings.Join(parts, ", ")
	}
	if generated {
		s += " — generated, do not edit directly"
	}
	return s
}
