package filemap

import (
	"fmt"
	"path/filepath"
	"regexp"
	"strings"

	"github.com/kaushal/skim/internal/digest"
)

var (
	// ocamlLetBind matches top-level let / let rec bindings.
	// Excludes "_" (wildcard) and "()" (unit expression let () = ...).
	// Groups: (1) binding name.
	ocamlLetBind = regexp.MustCompile(`^let\s+(?:rec\s+)?([a-z_][A-Za-z0-9_']*)`)

	// ocamlType matches type declarations including nonrec and single type
	// parameter forms: type t, type nonrec t, type 'a t.
	// Multi-parameter forms like type ('a,'b) t fall through — acceptable trade-off.
	// Groups: (1) type name.
	ocamlType = regexp.MustCompile(
		`^type\s+(?:nonrec\s+)?(?:'[a-z_][A-Za-z0-9_']*\s+)*([a-z_][A-Za-z0-9_']*)`)

	// ocamlModule matches module and module-type declarations.
	// Groups: (1) module name (always UpperCamelCase in OCaml).
	ocamlModule = regexp.MustCompile(`^module\s+(?:type\s+)?([A-Z][A-Za-z0-9_']*)`)

	// ocamlClass matches class and virtual class definitions.
	// Groups: (1) class name.
	ocamlClass = regexp.MustCompile(`^class\s+(?:virtual\s+)?([a-z_][A-Za-z0-9_']*)`)

	// ocamlVal matches val declarations in .mli interface files.
	// Groups: (1) value name.
	ocamlVal = regexp.MustCompile(`^val\s+([a-z_][A-Za-z0-9_']*)`)

	// ocamlException matches exception declarations.
	// Groups: (1) exception name (UpperCamelCase).
	ocamlException = regexp.MustCompile(`^exception\s+([A-Z][A-Za-z0-9_']*)`)

	ocamlGenerated = regexp.MustCompile(`DO NOT EDIT|auto.?generated|This file was (automatically )?generated|Generated by|@generated`)
)

// parseOCamlFile builds a FileMap for an OCaml source (.ml) or interface
// (.mli) file. OCaml top-level definitions always start at column 0, so
// indented lines are skipped — no depth tracking needed.
//
// .ml files:   collects let/let rec function names, type names, module names.
// .mli files:  collects val signatures, type names, module names.
//
// The entire file maps to one entry; the Kind label lists module/type names
// first, then function/val names, up to 4 with +N overflow.
func parseOCamlFile(src, filePath string) (digest.FileMap, bool) {
	lines := splitLines(src)
	if len(lines) == 0 {
		return digest.FileMap{}, false
	}
	if !hasOCamlStructure(lines) {
		return digest.FileMap{}, false
	}

	isInterface := strings.HasSuffix(strings.ToLower(filePath), ".mli")

	generated := false
	for _, l := range lines[:min(len(lines), 10)] {
		if ocamlGenerated.MatchString(l) {
			generated = true
			break
		}
	}

	var structural []string // module names, type names, exception names
	var defs []string       // let-bound functions (.ml) or val signatures (.mli)
	seenStructural := make(map[string]bool)
	seenDefs := make(map[string]bool)
	commentDepth := 0

	for _, raw := range lines {
		trimmed := strings.TrimSpace(raw)
		if trimmed == "" {
			continue
		}

		// (* ... *) block comments, nestable.
		depthAtStart := commentDepth
		commentDepth = updateOCamlCommentDepth(raw, commentDepth)
		if depthAtStart > 0 {
			continue
		}

		// Skip indented lines — they are continuation lines inside definitions
		// or bodies of module/class/struct/sig blocks.
		if len(raw) > 0 && (raw[0] == ' ' || raw[0] == '\t') {
			continue
		}

		// Skip line that starts a block comment (nothing useful before (*).
		if strings.HasPrefix(trimmed, "(*") {
			continue
		}

		// Skip open / include / external at top level.
		if strings.HasPrefix(trimmed, "open ") ||
			strings.HasPrefix(trimmed, "include ") ||
			strings.HasPrefix(trimmed, "external ") ||
			trimmed == "open" {
			continue
		}

		// module / module type declaration.
		if m := ocamlModule.FindStringSubmatch(raw); m != nil {
			name := m[1]
			if !seenStructural[name] {
				structural = append(structural, name)
				seenStructural[name] = true
			}
			continue
		}

		// type declaration.
		if m := ocamlType.FindStringSubmatch(raw); m != nil {
			name := m[1]
			if !isOCamlKeyword(name) && !seenStructural[name] {
				structural = append(structural, name)
				seenStructural[name] = true
			}
			continue
		}

		// exception declaration.
		if m := ocamlException.FindStringSubmatch(raw); m != nil {
			name := m[1]
			if !seenStructural[name] {
				structural = append(structural, name)
				seenStructural[name] = true
			}
			continue
		}

		// class / class virtual.
		if m := ocamlClass.FindStringSubmatch(raw); m != nil {
			name := m[1]
			if !isOCamlKeyword(name) && !seenDefs[name] {
				defs = append(defs, name)
				seenDefs[name] = true
			}
			continue
		}

		if isInterface {
			// .mli: val declarations.
			if m := ocamlVal.FindStringSubmatch(raw); m != nil {
				name := m[1]
				if name != "_" && !isOCamlKeyword(name) && !seenDefs[name] {
					defs = append(defs, name)
					seenDefs[name] = true
				}
			}
		} else {
			// .ml: let bindings (functions and values).
			if m := ocamlLetBind.FindStringSubmatch(raw); m != nil {
				name := m[1]
				if name != "_" && !isOCamlKeyword(name) && !seenDefs[name] {
					defs = append(defs, name)
					seenDefs[name] = true
				}
			}
		}
	}

	if len(structural) == 0 && len(defs) == 0 {
		return digest.FileMap{}, false
	}

	base := filepath.Base(filePath)
	stem := strings.TrimSuffix(strings.TrimSuffix(base, ".mli"), ".ml")

	combined := append(structural, defs...)
	label := ocamlLabel(stem, combined)
	summary := ocamlSummary(stem, len(structural), len(defs), isInterface, generated)

	var symbols []string
	for _, s := range structural {
		symbols = append(symbols, "type "+s)
	}
	for _, d := range defs {
		if isInterface {
			symbols = append(symbols, "val "+d)
		} else {
			symbols = append(symbols, "fn "+d)
		}
	}

	return digest.FileMap{
		Summary: summary,
		Map: []digest.MapEntry{{
			Lines: lineRange(1, len(lines)),
			Kind:  label,
		}},
		Symbols: symbols,
	}, true
}

// updateOCamlCommentDepth scans line and returns the updated (* *) nesting
// depth. OCaml block comments are nestable; a boolean would exit too early on
// the inner *) of (* (* inner *) still outer *).
// At depth 0, (* increments; at any depth, (* increments and *) decrements.
func updateOCamlCommentDepth(line string, depth int) int {
	for i := 0; i < len(line); i++ {
		ch := line[i]
		next := byte(0)
		if i+1 < len(line) {
			next = line[i+1]
		}
		if ch == '(' && next == '*' {
			depth++
			i++
		} else if ch == '*' && next == ')' {
			if depth > 0 {
				depth--
			}
			i++
		}
	}
	return depth
}

func isOCamlKeyword(s string) bool {
	switch s {
	case "and", "as", "assert", "asr", "begin", "class", "constraint",
		"do", "done", "downto", "else", "end", "exception", "external",
		"false", "for", "fun", "function", "functor", "if", "in",
		"include", "inherit", "initializer", "land", "lazy", "let",
		"lor", "lsl", "lsr", "lxor", "match", "method", "mod",
		"module", "mutable", "new", "nonrec", "object", "of",
		"open", "or", "private", "rec", "sig", "struct", "then",
		"to", "true", "try", "type", "val", "virtual", "when",
		"while", "with":
		return true
	}
	return false
}

func ocamlLabel(stem string, names []string) string {
	label := "module " + stem
	if len(names) == 0 {
		return label
	}
	displayed := names
	suffix := ""
	if len(displayed) > 4 {
		displayed = displayed[:4]
		suffix = fmt.Sprintf(" (+%d)", len(names)-4)
	}
	return label + " — " + strings.Join(displayed, ", ") + suffix
}

func ocamlSummary(stem string, structuralCount, defCount int, isInterface, generated bool) string {
	kind := "OCaml"
	if isInterface {
		kind = "OCaml interface"
	}
	s := kind + " — " + stem
	var parts []string
	if structuralCount == 1 {
		parts = append(parts, "1 type")
	} else if structuralCount > 1 {
		parts = append(parts, fmt.Sprintf("%d types", structuralCount))
	}
	defLabel := "function"
	if isInterface {
		defLabel = "val"
	}
	if defCount == 1 {
		parts = append(parts, "1 "+defLabel)
	} else if defCount > 1 {
		parts = append(parts, fmt.Sprintf("%d %ss", defCount, defLabel))
	}
	if len(parts) > 0 {
		s += ", " + strings.Join(parts, ", ")
	}
	if generated {
		s += " — generated, do not edit directly"
	}
	return s
}

func hasOCamlStructure(lines []string) bool {
	for _, l := range lines {
		if ocamlLetBind.MatchString(l) ||
			ocamlType.MatchString(l) ||
			ocamlModule.MatchString(l) ||
			ocamlClass.MatchString(l) ||
			ocamlVal.MatchString(l) {
			return true
		}
	}
	return false
}
