package filemap

import (
	"fmt"
	"regexp"
	"strings"

	"github.com/kaushal/skim/internal/digest"
)

var (
	// phpTopBlock matches a PHP type declaration.
	// Groups: (1) kind phrase, (2) name
	phpTopBlock = regexp.MustCompile(
		`^\s*(?:(?:#\[[^\]]*\]\s*)*)` + // optional PHP 8 attributes #[...]
			`((?:(?:abstract|final|readonly)\s+)*` + // type-shaping qualifiers in group 1
			`(?:class|interface|trait|enum))\s+` +
			`([A-Za-z_][A-Za-z0-9_]*)`)
	// phpMethod matches a PHP method/function declaration.
	// Groups: (1) name
	phpMethod = regexp.MustCompile(
		`^\s*(?:(?:#\[[^\]]*\]\s*)*)` + // optional PHP 8 attributes
			`(?:(?:public|protected|private|static|abstract|final|readonly)\s+)*` +
			`function\s+([A-Za-z_][A-Za-z0-9_]*)`)
	// phpComment matches PHP single-line comments (both // and #).
	phpComment = regexp.MustCompile(`^\s*(?://|#)`)
	// phpNamespace matches PHP namespace declarations (file-scoped; no braces).
	phpNamespace = regexp.MustCompile(`^\s*namespace\s+[\w\\]+\s*;`)
	// phpUse matches use/require/include lines to skip.
	phpUse = regexp.MustCompile(`^\s*(?:use|require|include|require_once|include_once)\s`)
	// phpAttribute matches standalone PHP 8 attribute lines.
	phpAttribute = regexp.MustCompile(`^\s*#\[`)
	// phpOpenTag matches the opening PHP tag to skip.
	phpOpenTag = regexp.MustCompile(`^\s*<\?php`)
	// phpGenerated detects generated PHP files.
	phpGenerated = regexp.MustCompile(`DO NOT EDIT|auto.?generated|This file was (automatically )?generated|Generated by|@generated`)
)

// phpBlock tracks one PHP type declaration while parsing.
type phpBlock struct {
	kind      string
	name      string
	startLine int
	endLine   int
	methods   []string
}

// parsePhpFile builds a FileMap from a PHP source file. Each top-level
// type declaration (class, interface, trait, enum) becomes one map entry;
// the Kind label lists up to 4 method names with +N overflow.
func parsePhpFile(src, _ string) (digest.FileMap, bool) {
	lines := splitLines(src)
	if len(lines) == 0 {
		return digest.FileMap{}, false
	}
	if !hasPhpStructure(lines) {
		return digest.FileMap{}, false
	}

	generated := false
	for _, l := range lines[:min(len(lines), 10)] {
		if phpGenerated.MatchString(l) {
			generated = true
			break
		}
	}

	var blocks []*phpBlock
	var cur *phpBlock
	var pendingBlock *phpBlock
	depth := 0
	bcDepth := 0
	inDouble := false // persistent: true while inside a multi-line double-quoted string
	inSingle := false // persistent: true while inside a multi-line single-quoted string
	heredocEnd := ""  // non-empty while inside a heredoc/nowdoc; holds the closing marker

	closeBlock := func(endLine int) {
		if cur != nil {
			cur.endLine = endLine
			blocks = append(blocks, cur)
			cur = nil
		}
	}

	for i, raw := range lines {
		lineNo := i + 1
		trimmed := strings.TrimSpace(raw)

		if trimmed == "" {
			continue
		}

		// Heredoc/nowdoc tracking — must come before startedInBC so we skip
		// heredoc content regardless of block-comment state.
		if heredocEnd != "" {
			// The closing marker must be at the start of the line (PHP < 7.3 requires
			// column 0; PHP 7.3+ allows indentation, but we check trimmed for safety).
			if trimmed == heredocEnd || trimmed == heredocEnd+";" {
				heredocEnd = ""
			}
			continue
		}

		startedInBC := bcDepth > 0

		// Detect a heredoc/nowdoc opener only in actual code context (outside
		// comments and strings). phpFindHeredocLabel returns "" when the <<< token
		// is inside a block comment, a // or # comment, or a quoted string.
		if label := phpFindHeredocLabel(raw, bcDepth, inDouble, inSingle); label != "" {
			heredocEnd = label
			// phpFindHeredocLabel only returns a label when not inside a string,
			// so these are already false — reset defensively.
			inDouble = false
			inSingle = false
			continue
		}

		if pendingBlock != nil {
			d := phpNetBraces(raw, &bcDepth, &inDouble, &inSingle)
			if d > 0 {
				cur = pendingBlock
				depth = d
				pendingBlock = nil
			} else if d < 0 {
				pendingBlock = nil
			}
			continue
		}

		if cur != nil {
			// Collect methods at depth 1 BEFORE updating depth.
			if !startedInBC && !inDouble && !inSingle && depth == 1 && !phpAttribute.MatchString(raw) {
				if m := phpMethod.FindStringSubmatch(trimmed); m != nil {
					name := m[1]
					if !isPhpKeyword(name) {
						cur.methods = append(cur.methods, name)
					}
				}
			}
			depth += phpNetBraces(raw, &bcDepth, &inDouble, &inSingle)
			if depth <= 0 {
				closeBlock(lineNo)
				depth = 0
			}
			continue
		}

		// Top level.
		if startedInBC || inDouble || inSingle {
			phpNetBraces(raw, &bcDepth, &inDouble, &inSingle)
			continue
		}
		if phpOpenTag.MatchString(raw) {
			continue
		}
		if phpComment.MatchString(raw) {
			continue
		}
		if phpNamespace.MatchString(raw) {
			continue
		}
		if phpUse.MatchString(raw) {
			continue
		}
		if phpAttribute.MatchString(raw) {
			continue
		}

		if m := phpTopBlock.FindStringSubmatch(trimmed); m != nil {
			kind := strings.TrimSpace(m[1])
			b := &phpBlock{kind: kind, name: m[2], startLine: lineNo}
			d := phpNetBraces(raw, &bcDepth, &inDouble, &inSingle)
			if d > 0 {
				cur = b
				depth = d
			} else {
				// Multi-line header (implements/extends on next line).
				if !strings.Contains(trimmed, ";") {
					pendingBlock = b
				}
			}
			continue
		}

		phpNetBraces(raw, &bcDepth, &inDouble, &inSingle)
	}
	closeBlock(len(lines))

	if len(blocks) == 0 {
		return digest.FileMap{}, false
	}

	var entries []digest.MapEntry
	var symbols []string
	for _, b := range blocks {
		label := phpBlockLabel(b)
		if len(symbols) < 40 {
			symbols = append(symbols, b.kind+" "+b.name)
		}
		entries = append(entries, digest.MapEntry{
			Lines: lineRange(b.startLine, b.endLine),
			Kind:  label,
		})
	}

	return digest.FileMap{
		Summary: phpSummary(blocks, generated),
		Map:     entries,
		Symbols: symbols,
	}, true
}

// phpNetBraces counts net brace depth for a PHP line, ignoring braces inside
// double-quoted strings, single-quoted strings, // and # comments, and
// /* */ block comments. inDouble and inSingle are persistent across calls so
// that multi-line quoted strings are tracked correctly.
func phpNetBraces(line string, bcDepth *int, inDouble *bool, inSingle *bool) int {
	depth := 0
	for i := 0; i < len(line); i++ {
		ch := line[i]
		if *bcDepth > 0 {
			if ch == '*' && i+1 < len(line) && line[i+1] == '/' {
				*bcDepth--
				i++
			}
			continue
		}
		if *inDouble {
			if ch == '\\' {
				i++
				continue
			}
			if ch == '"' {
				*inDouble = false
			}
			continue
		}
		if *inSingle {
			// Single-quoted PHP strings: only \\ and \' are escape sequences.
			if ch == '\\' && i+1 < len(line) {
				next := line[i+1]
				if next == '\\' || next == '\'' {
					i++
					continue
				}
			}
			if ch == '\'' {
				*inSingle = false
			}
			continue
		}
		switch ch {
		case '"':
			*inDouble = true
		case '\'':
			*inSingle = true
		case '/':
			if i+1 < len(line) && line[i+1] == '/' {
				return depth
			}
			if i+1 < len(line) && line[i+1] == '*' {
				*bcDepth = 1
				i++
			}
		case '#':
			// PHP single-line comment: # and also #[ (attribute) — only # alone.
			if i+1 >= len(line) || line[i+1] != '[' {
				return depth
			}
		case '{':
			depth++
		case '}':
			depth--
		}
	}
	return depth
}

// phpFindHeredocLabel scans a line for a heredoc/nowdoc opener (<<<LABEL or
// <<<'LABEL') that appears in actual PHP code context — outside block comments
// (bcDepth > 0), single-line comments (// and #), and quoted strings. Returns
// the label, or "" when none is found or the <<< is not in code context.
func phpFindHeredocLabel(line string, bcDepth int, inDouble bool, inSingle bool) string {
	if bcDepth > 0 || inDouble || inSingle {
		return ""
	}
	localDouble := false
	localSingle := false
	for i := 0; i < len(line); i++ {
		ch := line[i]
		if localDouble {
			if ch == '\\' {
				i++
				continue
			}
			if ch == '"' {
				localDouble = false
			}
			continue
		}
		if localSingle {
			if ch == '\\' && i+1 < len(line) {
				next := line[i+1]
				if next == '\\' || next == '\'' {
					i++
					continue
				}
			}
			if ch == '\'' {
				localSingle = false
			}
			continue
		}
		switch ch {
		case '/':
			if i+1 < len(line) && line[i+1] == '/' {
				return "" // rest of line is a // comment
			}
			if i+1 < len(line) && line[i+1] == '*' {
				return "" // block comment opens; <<< cannot precede this on the same line in code
			}
		case '#':
			if i+1 >= len(line) || line[i+1] != '[' {
				return "" // # comment
			}
		case '"':
			localDouble = true
		case '\'':
			localSingle = true
		case '<':
			if i+2 < len(line) && line[i+1] == '<' && line[i+2] == '<' {
				i += 3
				nowdoc := i < len(line) && line[i] == '\''
				if nowdoc {
					i++
				}
				start := i
				for i < len(line) {
					c := line[i]
					if c == '_' || (c >= 'A' && c <= 'Z') || (c >= 'a' && c <= 'z') ||
						(i > start && c >= '0' && c <= '9') {
						i++
					} else {
						break
					}
				}
				label := line[start:i]
				if len(label) == 0 {
					return ""
				}
				return label
			}
		}
	}
	return ""
}

// isPhpKeyword filters common false positives from phpMethod.
func isPhpKeyword(s string) bool {
	switch s {
	case "if", "else", "elseif", "for", "foreach", "while", "do", "switch",
		"case", "break", "continue", "return", "echo", "print", "die", "exit",
		"try", "catch", "throw", "new", "class", "interface", "trait", "enum",
		"namespace", "use", "include", "require", "match", "list", "array":
		return true
	}
	return false
}

// phpBlockLabel builds the Kind label for a PHP block entry.
func phpBlockLabel(b *phpBlock) string {
	label := b.kind + " " + b.name
	if len(b.methods) == 0 {
		return label
	}
	displayed := b.methods
	suffix := ""
	if len(displayed) > 4 {
		displayed = displayed[:4]
		suffix = fmt.Sprintf(" (+%d)", len(b.methods)-4)
	}
	return label + " — " + strings.Join(displayed, ", ") + suffix
}

// phpSummary builds the top-level summary line.
func phpSummary(blocks []*phpBlock, generated bool) string {
	counts := map[string]int{}
	methodCount := 0
	for _, b := range blocks {
		counts[b.kind]++
		methodCount += len(b.methods)
	}

	ordered := []string{
		"class", "abstract class", "final class", "readonly class",
		"interface", "trait", "enum",
	}
	var parts []string
	for _, k := range ordered {
		n := counts[k]
		if n == 0 {
			continue
		}
		if n == 1 {
			parts = append(parts, "1 "+k)
		} else {
			words := strings.Fields(k)
			last := words[len(words)-1]
			if strings.HasSuffix(last, "s") || strings.HasSuffix(last, "x") ||
				strings.HasSuffix(last, "ch") || strings.HasSuffix(last, "sh") {
				last += "es"
			} else {
				last += "s"
			}
			words[len(words)-1] = last
			parts = append(parts, fmt.Sprintf("%d %s", n, strings.Join(words, " ")))
		}
	}
	if methodCount == 1 {
		parts = append(parts, "1 method")
	} else if methodCount > 1 {
		parts = append(parts, fmt.Sprintf("%d methods", methodCount))
	}

	summary := "PHP — " + strings.Join(parts, ", ")
	if generated {
		summary += " — generated, do not edit directly"
	}
	return summary
}

// hasPhpStructure returns true when at least one class/interface/trait/enum
// declaration is present.
func hasPhpStructure(lines []string) bool {
	for _, l := range lines {
		if phpTopBlock.MatchString(l) {
			return true
		}
	}
	return false
}
