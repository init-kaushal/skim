func TestGenerate_Proto_ServiceRPCsInKind(t *testing.T) {
	// RPCs should appear in the service's Kind label (up to 4).
	src := `syntax = "proto3";
package gateway.v1;

message Req {}
message Res {}

service GatewayService {
  rpc Create(Req) returns (Res);
  rpc Read(Req) returns (Res);
  rpc Update(Req) returns (Res);
  rpc Delete(Req) returns (Res);
  rpc List(Req) returns (Res);
}
`
	fm, ok := filemap.Generate(src, "gateway.proto")
	if !ok {
		t.Fatal("expected deterministic map")
	}
	var svcEntry string
	for _, e := range fm.Map {
		if strings.Contains(e.Kind, "service GatewayService") {
			svcEntry = e.Kind
		}
	}
	if svcEntry == "" {
		t.Fatal("expected service entry in map")
	}
	// 5 RPCs — should show first 4 and (+1) suffix.
	if !strings.Contains(svcEntry, "(+1)") {
		t.Errorf("expected (+1) for 5th RPC, got: %s", svcEntry)
	}
	if !strings.Contains(svcEntry, "Create") {
		t.Errorf("expected Create in RPC list, got: %s", svcEntry)
	}
}
